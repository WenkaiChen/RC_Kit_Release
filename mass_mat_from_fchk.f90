SUBROUTINE MASS_MAT(N_ATOMS,N_MODE,FILENAME,ATOM_MASS,MASSMAT)
IMPLICIT NONE

INTEGER(KIND=4) :: N_ATOMS
INTEGER(KIND=4) :: N_MODE
CHARACTER*200 :: FILENAME
REAL(KIND=8) :: ATOM_MASS(N_ATOMS)
REAL(KIND=8) :: MASSMAT(N_MODE,N_MODE)

INTEGER(KIND=4) :: I,J

INTEGER(KIND=4),PARAMETER :: FILEID=13
REAL(KIND=8),PARAMETER :: AMU2KG=1.66053878D-27
REAL(KIND=8),PARAMETER :: AMU2AU=1822.8884271805

OPEN(FILEID,FILE=FILENAME,STATUS="OLD")

CALL LOCALLABEL(FILEID,"Real atomic weights")
WRITE(11,*) "Found where the data of atomic masses are."
READ(FILEID,*)
READ(FILEID,*) ATOM_MASS
WRITE(11,*) "***********************************ATOMIC MASSES**********************************"
WRITE(11,"(6(F12.6))") ATOM_MASS
WRITE(11,*) "*********************************ATOMIC MASSES END********************************"

MASSMAT=0
DO I=1,N_ATOMS
  DO J=(I-1)*3+1,I*3
    MASSMAT(J,J)=ATOM_MASS(I)
  END DO
END DO

ATOM_MASS=ATOM_MASS*AMU2AU
MASSMAT=MASSMAT*AMU2AU
CLOSE(FILEID)
END SUBROUTINE
