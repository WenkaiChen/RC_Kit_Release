SUBROUTINE HUANG_FACTOR(N_MODE,FREQ,DELTA_Q,S,S_I,S_EFF,FREQ_EFF,SIGMA)
IMPLICIT NONE

INTEGER(KIND=4) :: N_MODE
REAL(KIND=8) :: FREQ(N_MODE)
REAL(KIND=8) :: DELTA_Q(N_MODE)
REAL(KIND=8) :: S
REAL(KIND=8) :: S_I(N_MODE)
REAL(KIND=8) :: S_EFF,FREQ_EFF
REAL(KIND=8) :: SIGMA

INTEGER(KIND=4) :: I
REAL(KIND=8) :: WAVENUM_EFF

REAL(KIND=8),PARAMETER :: HBAR=1.054571800D-34
REAL(KIND=8),PARAMETER :: AMU2KG=1.66053878D-27
REAL(KIND=8),PARAMETER :: B2M=0.529177249D-10
REAL(KIND=8),PARAMETER :: AU2J=4.35974434D-18
REAL(KIND=8),PARAMETER :: PI=3.1415926535897932384
REAL(KIND=8),PARAMETER :: J2EV=6.241143E18
REAL(KIND=8),PARAMETER :: AUT2S=2.418884254E-17

SIGMA=0.0

DO I=1,N_MODE,1
  S_I(I)=2*PI*FREQ(I)*(DELTA_Q(I)**2)/2.0
  WRITE(11,"('MODE:',i5,' S factor:',F15.5,' Freq(cm-1):',F10.4)") I,S_I(I),FREQ(I)/AUT2S/2.99792458D10
END DO
WRITE(11,*) "*************************HUANG FACTOR************************************"

WRITE(11,*)
DO I=1,N_MODE,1

  IF ( S_I(I)>0.01 .AND. FREQ(I) > 2.997913D13*AUT2S .AND. FREQ(I)< 5.396244E13*AUT2S) THEN

    WRITE(11,"('MODE:',I5,' Effective S factor:',F15.5,' Freq(cm-1):',F10.4)") I,S_I(I),FREQ(I)/AUT2S/2.99792458D10
    S_EFF=S_EFF+S_I(I)
    SIGMA=SIGMA+FREQ(I)*S_I(I)*2.0*PI
  END IF
END DO
WRITE(11,*) "***********************HUANG FACTOR END**********************************"

IF ( S_EFF>0.01 ) THEN
  FREQ_EFF=SIGMA/(S_EFF*2*PI)
ELSE
  FREQ_EFF=0.0
END IF

WAVENUM_EFF=FREQ_EFF/AUT2S/2.99792458D10

WRITE(11,"('Effective frequency: ',F10.4,' cm-1.')") WAVENUM_EFF
WRITE(11,"('Effective HUANG-RHYS Factor Sum: ',1PE12.4)") S_EFF
WRITE(11,"('Hbar*W_eff: ',F10.6,' eV.')") FREQ_EFF*AU2J*J2EV

S=SUM(S_I)
WRITE(11,"('Total S factor is :',F10.5)") S
END SUBROUTINE
