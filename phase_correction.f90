SUBROUTINE PHASE_CORRECTION(THETA_01, THETA_02, THETA_00, G, T)
IMPLICIT NONE

REAL(KIND=8) :: THETA_01, THETA_02, THETA_00
REAL(KIND=8),INTENT(IN) :: T
COMPLEX(KIND=8) :: G

REAL(KIND=8), PARAMETER :: PI = 3.141592653589793D0
THETA_02 = atan(AIMAG(G)/REAL(G))/PI*180
IF (AIMAG(G) < 0.0) THEN
  IF (REAL(G) < 0.0 ) THEN
    THETA_02 = THETA_02-180
  END IF
ELSE IF (AIMAG(G) > 0.0 ) THEN
  IF (REAL(G ) < 0.0 ) THEN
    THETA_02 = THETA_02 + 180
  END IF
END IF
IF (T==1.0D-40) THEN
  THETA_01 = THETA_02
  THETA_00 = 1.0D0
END IF

IF ((THETA_02*THETA_01 < 0.0D0) .AND. ((ABS(THETA_01)+ABS(THETA_02)> 90.0D0) .AND. ((ABS(THETA_01)+ABS(THETA_02))<270.0D0))) THEN
  THETA_00 = -THETA_00
ELSE IF ((ABS(THETA_01)+ABS(THETA_02))<270.0D0 .AND. ABS(THETA_01-THETA_02)>90.0D0) THEN
  THETA_00 = -THETA_00
END IF
G = DCMPLX(THETA_00*REAL(G),THETA_00*AIMAG(G))
THETA_01 = THETA_02
END SUBROUTINE PHASE_CORRECTION
