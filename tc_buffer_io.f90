MODULE TC_BUFFER_IO
IMPLICIT NONE
INTEGER, PARAMETER :: TC_LINE_LEN = 512
CHARACTER(LEN=TC_LINE_LEN), ALLOCATABLE, SAVE :: TC_LINES(:)
INTEGER, SAVE :: TC_COUNT = 0
INTEGER, SAVE :: TC_CAPACITY = 0
CONTAINS
SUBROUTINE TC_BUFFER_INIT(ESTIMATE_LINES)
INTEGER, INTENT(IN) :: ESTIMATE_LINES
INTEGER :: NALLOC
TC_COUNT = 0
IF (ALLOCATED(TC_LINES)) DEALLOCATE(TC_LINES)
NALLOC = MAX(1024, ESTIMATE_LINES)
ALLOCATE(TC_LINES(NALLOC))
TC_CAPACITY = NALLOC
END SUBROUTINE TC_BUFFER_INIT

SUBROUTINE TC_BUFFER_ADD(LINE)
CHARACTER(LEN=*), INTENT(IN) :: LINE
CHARACTER(LEN=TC_LINE_LEN), ALLOCATABLE :: TMP(:)
INTEGER :: NEW_CAP
IF (.NOT. ALLOCATED(TC_LINES)) THEN
  ALLOCATE(TC_LINES(1024))
  TC_CAPACITY = 1024
  TC_COUNT = 0
END IF
IF (TC_COUNT >= TC_CAPACITY) THEN
  NEW_CAP = MAX(1024, 2*TC_CAPACITY)
  ALLOCATE(TMP(NEW_CAP))
  IF (TC_COUNT > 0) TMP(1:TC_COUNT) = TC_LINES(1:TC_COUNT)
  CALL MOVE_ALLOC(TMP, TC_LINES)
  TC_CAPACITY = NEW_CAP
END IF
TC_COUNT = TC_COUNT + 1
TC_LINES(TC_COUNT) = ' '
IF (LEN_TRIM(LINE) > 0) THEN
  TC_LINES(TC_COUNT) = LINE(1:MIN(LEN_TRIM(LINE), TC_LINE_LEN))
END IF
END SUBROUTINE TC_BUFFER_ADD

SUBROUTINE TC_BUFFER_FLUSH(UNIT_ID)
INTEGER, INTENT(IN) :: UNIT_ID
INTEGER :: I
IF (.NOT. ALLOCATED(TC_LINES)) RETURN
DO I = 1, TC_COUNT
  WRITE(UNIT_ID,'(A)') TRIM(TC_LINES(I))
END DO
END SUBROUTINE TC_BUFFER_FLUSH

SUBROUTINE TC_BUFFER_FREE()
IF (ALLOCATED(TC_LINES)) DEALLOCATE(TC_LINES)
TC_COUNT = 0
TC_CAPACITY = 0
END SUBROUTINE TC_BUFFER_FREE
END MODULE TC_BUFFER_IO
