SUBROUTINE INER_TRANS(N_ATOMS,N_MODE,ATMNU,ATMMS,COORD,L_MATRIX)

INTEGER(KIND=4) :: N_ATOMS
INTEGER(KIND=4) :: N_MODE
INTEGER(KIND=4) :: ATMNU(N_ATOMS)
REAL(KIND=8) :: ATMMS(N_ATOMS)
REAL(KIND=8) :: COORD(N_MODE)
REAL(KIND=8) :: L_MATRIX(N_MODE,N_MODE)

INTEGER(KIND=4) :: I,J
INTEGER(KIND=4) :: ISTAT
REAL(KIND=8) :: CENT_OF_MASS(3)
REAL(KIND=8) :: ROT_MAT(3,3)
REAL(KIND=8) :: EIGVALARR(3)
REAL(KIND=8) :: TEM_VEC(3)
REAL(KIND=8) :: ATOM_MASS_TOT
REAL(KIND=8) :: IN_TEN(3,3)
REAL(KIND=8),ALLOCATABLE :: C1(:,:)
REAL(KIND=8),ALLOCATABLE :: TRANS_MAT(:,:,:)
REAL(KIND=8) :: DIA_OFF(3)

REAL(KIND=8),PARAMETER :: AMU2KG=1.66053878D-27
REAL(KIND=8),PARAMETER :: AMU2AU=1822.8884271805
REAL(KIND=8),PARAMETER :: ANG2M=1.0D-10

ALLOCATE(C1(3,N_ATOMS))
ALLOCATE(TRANS_MAT(3,N_ATOMS,N_MODE))
CENT_OF_MASS=0.0
ROT_MAT=0.0
ATOM_MASS_TOT=0.0
IN_TEN=0.0
TEM_VEC=0.0
TRANS_MAT=0.0

J=0
DO I=1,N_ATOMS,1
  C1(1,I)=COORD(J+1)
  C1(2,I)=COORD(J+2)
  C1(3,I)=COORD(J+3)
  J=J+3
END DO

DO I=1,N_ATOMS,1
  IF (ATMNU(I) /= 1 ) THEN
    CENT_OF_MASS(1) = CENT_OF_MASS(1) + C1(1,I)*ATMMS(I)
    CENT_OF_MASS(2) = CENT_OF_MASS(2) + C1(2,I)*ATMMS(I)
    CENT_OF_MASS(3) = CENT_OF_MASS(3) + C1(3,I)*ATMMS(I)
    ATOM_MASS_TOT=ATOM_MASS_TOT+ATMMS(I)
  END IF
END DO

CENT_OF_MASS(1) = CENT_OF_MASS(1)/ATOM_MASS_TOT
CENT_OF_MASS(2) = CENT_OF_MASS(2)/ATOM_MASS_TOT
CENT_OF_MASS(3) = CENT_OF_MASS(3)/ATOM_MASS_TOT

DO I=1,N_ATOMS,1
  C1(1,I) = C1(1,I) - CENT_OF_MASS(1)
  C1(2,I) = C1(2,I) - CENT_OF_MASS(2)
  C1(3,I) = C1(3,I) - CENT_OF_MASS(3)
END DO

DO I=1,N_ATOMS,1
  IN_TEN(1,1) = IN_TEN(1,1) + (C1(2,I)**2 + C1(3,I)**2) * ATMMS(I)
  IN_TEN(2,2) = IN_TEN(2,2) + (C1(1,I)**2 + C1(3,I)**2) * ATMMS(I)
  IN_TEN(3,3) = IN_TEN(3,3) + (C1(1,I)**2 + C1(2,I)**2) * ATMMS(I)
  IN_TEN(2,1) = IN_TEN(2,1) - (C1(1,I) * C1(2,I) * ATMMS(I))
  IN_TEN(3,1) = IN_TEN(3,1) - (C1(1,I) * C1(3,I) * ATMMS(I))
  IN_TEN(3,2) = IN_TEN(3,2) - (C1(2,I) * C1(3,I) * ATMMS(I))
END DO
IN_TEN(1,2) = IN_TEN(2,1)
IN_TEN(1,3) = IN_TEN(3,1)
IN_TEN(2,3) = IN_TEN(3,2)

CALL DIAGSYMAT(3,IN_TEN,ROT_MAT,EIGVALARR,ISTAT)

IF (ISTAT==0) WRITE(*,*) "DIAGONALIZATION PASSED IN INER_TRANS."

TEM_VEC=ROT_MAT(:,1)
ROT_MAT(:,1)=ROT_MAT(:,3)
ROT_MAT(:,3)=TEM_VEC

ROT_MAT=TRANSPOSE(ROT_MAT)

C1=MATMUL(ROT_MAT,C1)

J=0
DO I=1,N_ATOMS,1
  COORD(J+1)=C1(1,I)
  COORD(J+2)=C1(2,I)
  COORD(J+3)=C1(3,I)
  J=J+3
END DO

TRANS_MAT=RESHAPE(L_MATRIX,(/3,N_ATOMS,N_MODE/))

DO I=1,N_MODE,1
  TRANS_MAT(:,:,I)=MATMUL(ROT_MAT,TRANS_MAT(:,:,I))
END DO

L_MATRIX=RESHAPE(TRANS_MAT,(/N_MODE,N_MODE/))

DEALLOCATE(C1)
DEALLOCATE(TRANS_MAT)
END SUBROUTINE
