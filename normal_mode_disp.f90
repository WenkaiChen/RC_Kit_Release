SUBROUTINE NOR_DIS_WITH_DUSH(N_ATOMS,N_MODE,FILENAME_1,FILENAME_2,L_MATRIX1,L_MATRIX2,&
  ATMMS1,ATMMS2,MASS_MAT1,MASS_MAT2,DELTA_Q,DUSHIN_FILE,&
  DUS_MAT,NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES,SUB)
IMPLICIT NONE

INTEGER(KIND=4) :: N_ATOMS
INTEGER(KIND=4) :: N_MODE
INTEGER(KIND=4) :: NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES(1000)
INTEGER(KIND=4) :: SUB
CHARACTER*200 :: FILENAME_1
CHARACTER*200 :: FILENAME_2
CHARACTER*200 :: DUSHIN_FILE
REAL(KIND=8) :: L_MATRIX1(N_MODE,N_MODE)
REAL(KIND=8) :: L_MATRIX2(N_MODE,N_MODE)
REAL(KIND=8) :: ATMMS1(N_ATOMS)
REAL(KIND=8) :: ATMMS2(N_ATOMS)
REAL(KIND=8) :: MASS_MAT1(N_MODE,N_MODE)
REAL(KIND=8) :: MASS_MAT2(N_MODE,N_MODE)
REAL(KIND=8) :: DELTA_Q(N_MODE)
REAL(KIND=8) :: DUS_MAT(N_MODE,N_MODE)

INTEGER(KIND=4) :: I
INTEGER(KIND=4),PARAMETER :: F1_ID=14
INTEGER(KIND=4),PARAMETER :: F2_ID=15
INTEGER(KIND=4),ALLOCATABLE :: ATMNU1(:)
INTEGER(KIND=4),ALLOCATABLE :: ATMNU2(:)
REAL(KIND=8),ALLOCATABLE :: COORD1(:)
REAL(KIND=8),ALLOCATABLE :: COORD2(:)
REAL(KIND=8),ALLOCATABLE :: COORD_SHIFT(:)
REAL(KIND=8),ALLOCATABLE :: L_MAT1_TRANS(:,:)
REAL(KIND=8),ALLOCATABLE :: L_MAT2_TRANS(:,:)
REAL(KIND=8),ALLOCATABLE :: Q1(:),Q2(:)

REAL(KIND=8),PARAMETER :: B2M=0.529177249D-10
REAL(KIND=8),PARAMETER :: B2ANG=5.291772D-1
REAL(KIND=8),PARAMETER :: ANG2M=1.0D-10
REAL(KIND=8),PARAMETER :: AU2KG=9.1093826D-31

ALLOCATE(ATMNU1(N_ATOMS))
ALLOCATE(ATMNU2(N_ATOMS))
ALLOCATE(COORD1(N_MODE))
ALLOCATE(COORD2(N_MODE))
ALLOCATE(COORD_SHIFT(N_MODE))
ALLOCATE(L_MAT1_TRANS(N_MODE,N_MODE))
ALLOCATE(L_MAT2_TRANS(N_MODE,N_MODE))
ALLOCATE(Q1(N_MODE),Q2(N_MODE))
COORD_SHIFT=0
DUS_MAT=0
L_MAT1_TRANS=0
L_MAT2_TRANS=0

OPEN(F1_ID,FILE=FILENAME_1,STATUS="OLD")
OPEN(F2_ID,FILE=FILENAME_2,STATUS="OLD")

CALL LOCALLABEL(F1_ID,"Atomic numbers")
WRITE(11,*) "Found where the data of atomic numbers of initial state are."
READ(F1_ID,*)
READ(F1_ID,*) ATMNU1
CALL LOCALLABEL(F2_ID,"Atomic numbers")
WRITE(11,*) "Found where the data of atomic numbers of final state are."
READ(F2_ID,*)
READ(F2_ID,*) ATMNU2

CALL LOCALLABEL(F1_ID,"Current cartesian coordinates")
WRITE(11,*) "Found where the data of cartesian coordinates of initial state are."
READ(F1_ID,*)
READ(F1_ID,*) COORD1
CALL LOCALLABEL(F2_ID,"Current cartesian coordinates")
WRITE(11,*) "Found where the data of cartesian coordinates of final state are."
READ(F2_ID,*)
READ(F2_ID,*) COORD2

CLOSE(F1_ID)
CLOSE(F2_ID)

CALL INER_TRANS(N_ATOMS,N_MODE,ATMNU1,ATMMS1,COORD1,L_MATRIX1)
CALL INER_TRANS(N_ATOMS,N_MODE,ATMNU2,ATMMS2,COORD2,L_MATRIX2)

CALL ALIGN_RIMERS(COORD1,COORD2,N_ATOMS,N_MODE,ATMNU1,ATMNU2,L_MATRIX2,11)

DO I=1,N_MODE,1
  COORD1(I)=COORD1(I)*DSQRT(MASS_MAT1(I,I))
  COORD2(I)=COORD2(I)*DSQRT(MASS_MAT2(I,I))
END DO

COORD_SHIFT=COORD1-COORD2
write(11,*) "***************MASS-WEIGHTED CARTESIAN COORD DIS***********************"
do i=1,n_mode,1
  write(11,"('Coord_shift: ',F10.5)") coord_shift(i)
end do
write(11,*) "***************MASS-WEIGHTED CARTESIAN COORD DIS END*******************"

L_MAT1_TRANS=TRANSPOSE(L_MATRIX1)
Q1 = MATMUL(L_MAT1_TRANS,COORD1)
L_MAT2_TRANS=TRANSPOSE(L_MATRIX2)
Q2 = MATMUL(L_MAT2_TRANS,COORD2)

DELTA_Q=MATMUL(L_MAT1_TRANS,COORD_SHIFT)
DUS_MAT=MATMUL(L_MAT1_TRANS,L_MATRIX2)

IF (NUM_ZERO_HUANG_MODE > 0) THEN
  DO I = 1,NUM_ZERO_HUANG_MODE,1
    DELTA_Q(ZERO_HUANG_FACTOR_MODES(I)) = 0.0D0
  END DO
END IF
write(11,"('********************************DELTA_Q************************')")
write(11,"(1(1pe16.8))") DELTA_Q
write(11,"('********************************DELTA_Q_END************************')")

WRITE(11,"('***********************DUSHIN MATRIX************************')")
OPEN(55,FILE=DUSHIN_FILE,STATUS="REPLACE")
WRITE(55,"(1pe16.8)") DUS_MAT
CLOSE(55)
WRITE(11,"('*********************DUSHIN MATRIX END************************')")

DEALLOCATE(ATMNU1)
DEALLOCATE(ATMNU2)
DEALLOCATE(COORD1)
DEALLOCATE(COORD2)
DEALLOCATE(COORD_SHIFT)
DEALLOCATE(L_MAT1_TRANS)
END SUBROUTINE
