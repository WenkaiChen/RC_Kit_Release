SUBROUTINE LOCALLABEL(FILEID,LABEL)
IMPLICIT NONE
INTEGER(KIND=4) :: FILEID,IERROR
CHARACTER*200 :: C200
CHARACTER(LEN=*) :: LABEL

REWIND(FILEID)

DO WHILE(.TRUE.)
  READ(FILEID,"(A)",IOSTAT=IERROR) C200
  IF (INDEX(C200,LABEL)/=0) THEN
    BACKSPACE(FILEID)
    RETURN
  END IF
  IF (IERROR/=0) EXIT
END DO

END SUBROUTINE
