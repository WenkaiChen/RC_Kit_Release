SUBROUTINE HESS2FREQ(N_ATOMS,N_MODE,HESSIAN_FILE,MASS_MAT,FREQ,L_MATRIX)
IMPLICIT NONE

INTEGER(KIND=4) :: N_ATOMS
INTEGER(KIND=4) :: N_MODE
CHARACTER*200 :: HESSIAN_FILE
REAL(KIND=8) :: MASS_MAT(N_MODE,N_MODE)
REAL(KIND=8) :: FREQ(N_MODE)
REAL(KIND=8) :: L_MATRIX(N_MODE,N_MODE)

INTEGER(KIND=4) :: I,J
INTEGER(KIND=4) :: ISTAT
REAL(KIND=8),ALLOCATABLE :: HESSIAN(:,:)
REAL(KIND=8),ALLOCATABLE :: MW_HESSIAN(:,:)
REAL(KIND=8),ALLOCATABLE :: FORCE_CONST(:)
REAL(KIND=8),ALLOCATABLE :: WAVENUM(:)

INTEGER(KIND=4),PARAMETER :: FILEID=12
REAL(KIND=8),PARAMETER :: PI=3.1415926535897932384
REAL(KIND=8),PARAMETER :: AUT2S=2.418884254E-17
REAL(KIND=8),PARAMETER :: AMU2KG=1.66053878D-27
REAL(KIND=8),PARAMETER :: B2M=0.529177249D-10
REAL(KIND=8),PARAMETER :: AU2J=4.35974434D-18

ALLOCATE(HESSIAN(N_MODE,N_MODE))
ALLOCATE(MW_HESSIAN(N_MODE,N_MODE))
ALLOCATE(FORCE_CONST(N_MODE))
ALLOCATE(WAVENUM(N_MODE))
HESSIAN=0.0

OPEN(FILEID,FILE=HESSIAN_FILE,STATUS="OLD")

WRITE(11,*) "Reading hessian matrix from .hess file..."
DO I=1,N_MODE,1
  READ(FILEID,*) (HESSIAN(I,J),J=1,N_MODE,1)
END DO

DO I=1,N_MODE,1
  DO J=1,N_MODE,1
    MW_HESSIAN(I,J)=HESSIAN(I,J)/DSQRT(MASS_MAT(I,I)*MASS_MAT(J,J))
  END DO
END DO

CALL DIAGSYMAT(N_MODE,MW_HESSIAN,L_MATRIX,FORCE_CONST,ISTAT)
IF (ISTAT==0) WRITE(11,*) "DIAGONALIZATION PASSED"

WRITE(11,*)"*************Force constant in Atomic Unit*******************************"
WRITE(11,"(5(1PE16.8))") FORCE_CONST
WRITE(11,*)"*******************Force constant END************************************"

WRITE(11,*)

DO I=1,N_MODE
  IF (FORCE_CONST(I)<0) THEN
    FREQ(I)=-DSQRT(ABS(FORCE_CONST(I)))/(2*PI)
  ELSE
    FREQ(I)=DSQRT(FORCE_CONST(I))/(2*PI)
  END IF
END DO

WAVENUM=FREQ/AUT2S/2.99792458D10
WRITE(11,*)"**********************UNSORTED FREQ. IN HZ**********************************"
WRITE(11,"(5(1PE16.8))") FREQ/AUT2S

WRITE(11,*)"********************UNSORTED FREQ. IN HZ END********************************"
CLOSE(FILEID)

DEALLOCATE(HESSIAN)
DEALLOCATE(MW_HESSIAN)
DEALLOCATE(FORCE_CONST)
DEALLOCATE(WAVENUM)
END SUBROUTINE HESS2FREQ
