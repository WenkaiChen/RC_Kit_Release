ALLOCATE(LAMBDA1_I(N_MODE),LAMBDA2_I(N_MODE))
ALLOCATE(DELTA_Q1(N_MODE),DELTA_Q2(N_MODE))
ALLOCATE(DUSHIN_MAT(N_MODE,N_MODE))

ALLOCATE(EV_INI(N_VIB),EV_FINAL(N_VIB))
ALLOCATE(OMEGA1(N_VIB,N_VIB),OMEGA2(N_VIB,N_VIB))
ALLOCATE(S1(N_VIB,N_VIB),S2(N_VIB,N_VIB))
ALLOCATE(B1(N_VIB,N_VIB),B2(N_VIB,N_VIB))
ALLOCATE(F(N_VIB,N_VIB),Z(N_VIB,1))
ALLOCATE(D(N_VIB,1))
