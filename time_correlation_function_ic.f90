IF (CAL_REO) THEN

  CALL MASS_MAT(N_ATOMS,N_MODE,INIT_FILENAME,ATOM_MASS1,MASS_MAT1)

  CALL MASS_MAT(N_ATOMS,N_MODE,FINAL_FILENAME,ATOM_MASS2,MASS_MAT2)

  CALL HESS2FREQ(N_ATOMS,N_MODE,HESSIAN_FILE_1,MASS_MAT1,INIT_FREQ,INIT_L_MATRIX)

  CALL HESS2FREQ(N_ATOMS,N_MODE,HESSIAN_FILE_2,MASS_MAT2,FINAL_FREQ,FINAL_L_MATRIX)

  IF (NAC_MODE == 1) THEN
    CALL DR2DQ_TRANS(N_MODE,MASS_MAT1,INIT_L_MATRIX,NAC_FILE,NAC_NM)
  ELSE IF (NAC_MODE == 2) THEN
    CALL READ_COUPLING_DQ(N_MODE,NAC_FILE,NAC_NM)
  ELSE
    WRITE(LOGID,*) "NAC_MODE IS NOT WELL SET. PLS CHECK..."
    STOP 200
  END IF

  CALL NOR_DIS_WITH_DUSH(N_ATOMS,N_MODE,INIT_FILENAME,FINAL_FILENAME,INIT_L_MATRIX,FINAL_L_MATRIX,&
    ATOM_MASS1,ATOM_MASS2,MASS_MAT1,MASS_MAT2,DELTA_Q1,'DUSHIN_1.TXT',&
    DUSHIN_MAT,NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES,SUB)

  DELTA_Q2=DELTA_Q1
  IF (USE_DUSCHINSKY) DELTA_Q2=MATMUL(TRANSPOSE(DUSHIN_MAT),DELTA_Q1)

  CALL HUANG_FACTOR(N_MODE,INIT_FREQ,DELTA_Q1,HUANG_RHYS_1,HUANG_RHYS_1_I,HUANG_RHYS_1_EFF,FREQ1_EFF,SIGMA)

  DO I=1,N_VIB,1
    IF ( .NOT. CRYSTAL ) THEN
      OMEGA1(I,I)=DCMPLX(INIT_FREQ(I+6)*2*PI,0.D0)
      OMEGA2(I,I)=DCMPLX(FINAL_FREQ(I+6)*2*PI,0.D0)
      EV_INI(I) = DCMPLX(INIT_FREQ(I+6)*2*PI,0.D0)
      EV_FINAL(I)=DCMPLX(FINAL_FREQ(I+6)*2*PI,0.D0)
      Z(I,1)=0
      D(I,1)=DCMPLX(DELTA_Q2(I+6),0.D0)
      NAC_VIB(I) = NAC_NM(I+6)
      IF (USE_DUSCHINSKY) THEN
        DO K=1,N_VIB,1
          J(I,K) = DUSHIN_MAT(I+6,K+6)
        END DO
      ELSE
        J(I,I) = DCMPLX(1.0D0,0.0D0)
      END IF
    ELSE
      OMEGA1(I,I)=DCMPLX(INIT_FREQ(I)*2*PI,0.D0)
      OMEGA2(I,I)=DCMPLX(FINAL_FREQ(I)*2*PI,0.D0)
      EV_INI(I) = DCMPLX(INIT_FREQ(I)*2*PI,0.D0)
      EV_FINAL(I)=DCMPLX(FINAL_FREQ(I)*2*PI,0.D0)
      Z(I,1)=0
      D(I,1)=DCMPLX(DELTA_Q2(I),0.D0)
      NAC_VIB(I) = NAC_NM(I)
      IF (USE_DUSCHINSKY) THEN
        DO K=1,N_VIB,1
          J(I,K) = DUSHIN_MAT(I,K)
        END DO
      ELSE
        J(I,I) = DCMPLX(1.0D0,0.0D0)
      END IF
    END IF

    LOOP: DO K=1,1000
      TMP_VALUE=EXP(-(REAL(EV_INI(I))*(K-0.5))*BE)
      IF (TMP_VALUE > 1.0D-15 .OR. (K .LE. 20)) THEN
        Z(I,1)=Z(I,1) + DCMPLX(TMP_VALUE,0.D0)
      ELSE
        EXIT LOOP
      END IF
    END DO LOOP
  END DO
  J=TRANSPOSE(J)
  WRITE(11,*) "************************NAC FOR NORMAL MODE*********************************"
  DO I=1,N_MODE,1
    WRITE(11,"('MODE:',i5,' NAC(AU):',1PE15.5)") I, NAC_NM(I)
  END DO
  WRITE(11,*) "*********************NAC FOR NORMAL MODE END********************************"
  WRITE(11,*) "************************NAC FOR VIBRATION MODE*********************************"
  DO I=1,N_VIB,1
    WRITE(11,"('MODE:',i5,' NAC(AU):',1PE15.5)") I, NAC_VIB(I)
  END DO
  WRITE(11,*) "*********************NAC FOR VIBRATION MODE END********************************"

  DO I=1,N_VIB,1
    DO K=1,N_VIB,1
      F(I,K)=DCMPLX(NAC_VIB(I),0.D0)*DCMPLX(NAC_VIB(K),0.D0)
    END DO
  END DO
