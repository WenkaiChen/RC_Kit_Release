SUBROUTINE CPU_IC13_INTEGRAL_DET_UNWRAP(STEPS_IN,A0,B0,INTEGRAL,IERR)
IMPLICIT NONE
INTEGER(KIND=4), INTENT(IN) :: STEPS_IN
REAL(KIND=8), INTENT(IN) :: A0, B0
REAL(KIND=8), INTENT(OUT) :: INTEGRAL
INTEGER(KIND=4), INTENT(OUT) :: IERR
INTEGER(KIND=4) :: STEPS_EFF, NPTS, II, LOCAL_IERR
REAL(KIND=8) :: H, T_CUR, WIN_LOCAL
REAL(KIND=8), ALLOCATABLE :: GREAL(:)
COMPLEX(KIND=8), ALLOCATABLE :: GBASE(:), PHASE_RATIO(:), GCORR(:)

IERR = 0
INTEGRAL = 0.0D0
STEPS_EFF = STEPS_IN
IF (STEPS_EFF <= 0) THEN
  IERR = -1301
  RETURN
END IF
NPTS = STEPS_EFF + 1
H = (B0-A0)/DBLE(STEPS_EFF)
ALLOCATE(GREAL(NPTS),GBASE(NPTS),PHASE_RATIO(NPTS),GCORR(NPTS))

DO II=1,NPTS,1
  T_CUR = A0 + DBLE(II-1)*H
  CALL GET_G_TIME_CORR_IC13_PARTS(T_CUR,GBASE(II),PHASE_RATIO(II),LOCAL_IERR)
  IF (LOCAL_IERR /= 0) THEN
    IERR = LOCAL_IERR
    DEALLOCATE(GREAL,GBASE,PHASE_RATIO,GCORR)
    RETURN
  END IF
END DO

CALL CPU_APPLY_DET_PHASE_UNWRAP(GBASE,PHASE_RATIO,GCORR,NPTS,LOCAL_IERR)
IF (LOCAL_IERR /= 0) THEN
  IERR = LOCAL_IERR
  DEALLOCATE(GREAL,GBASE,PHASE_RATIO,GCORR)
  RETURN
END IF

DO II=1,NPTS,1
  T_CUR = A0 + DBLE(II-1)*H
  WIN_LOCAL = 1.0D0
  IF (USE_DAMPING_FUNCTION) THEN
    WIN_LOCAL = GAUSS(T_CUR,0.0D0,1.0D0/DAMPING_WIDTH*3.335653E-12/AUT2S)
  END IF
  GREAL(II) = WIN_LOCAL*REAL(GCORR(II))
  IF (USE_DAMPING_FUNCTION) THEN
    WRITE(TC_LINE,"(F12.5,1PE20.10,1PE20.10)") T_CUR*2.418884326505D-2, GREAL(II), WIN_LOCAL
    CALL TC_BUFFER_ADD(TC_LINE)
  ELSE
    WRITE(TC_LINE,"(F12.5,1PE20.10)") T_CUR*2.418884326505D-2, GREAL(II)
    CALL TC_BUFFER_ADD(TC_LINE)
  END IF
END DO

CALL CPU_SIMPSON_FROM_VECTOR(GREAL,A0,B0,STEPS_EFF,INTEGRAL)
DEALLOCATE(GREAL,GBASE,PHASE_RATIO,GCORR)
END SUBROUTINE CPU_IC13_INTEGRAL_DET_UNWRAP

SUBROUTINE CPU_APPLY_DET_PHASE_UNWRAP(GBASE,PHASE_RATIO,GCORR,NPTS,IERR)
IMPLICIT NONE
INTEGER(KIND=4), INTENT(IN) :: NPTS
COMPLEX(KIND=8), INTENT(IN) :: GBASE(:), PHASE_RATIO(:)
COMPLEX(KIND=8), INTENT(OUT) :: GCORR(:)
INTEGER(KIND=4), INTENT(OUT) :: IERR
INTEGER(KIND=4) :: II
REAL(KIND=8) :: MAGP, THETA_RAW, THETA_PREV_RAW, THETA_UNWRAP, DELTA
COMPLEX(KIND=8) :: SQPH

IERR = 0
IF (NPTS <= 0) RETURN
THETA_PREV_RAW = 0.0D0
THETA_UNWRAP = 0.0D0

DO II=1,NPTS,1
  MAGP = ABS(PHASE_RATIO(II))
  IF (MAGP /= MAGP .OR. MAGP == 0.0D0) THEN
    IERR = -1310
    GCORR(II:NPTS) = DCMPLX(0.0D0,0.0D0)
    RETURN
  END IF
  THETA_RAW = ATAN2(AIMAG(PHASE_RATIO(II)),REAL(PHASE_RATIO(II)))
  IF (II == 1) THEN
    THETA_UNWRAP = THETA_RAW
  ELSE
    DELTA = THETA_RAW - THETA_PREV_RAW
    DO WHILE (DELTA > PI)
      DELTA = DELTA - 2.0D0*PI
    END DO
    DO WHILE (DELTA <= -PI)
      DELTA = DELTA + 2.0D0*PI
    END DO
    THETA_UNWRAP = THETA_UNWRAP + DELTA
  END IF
  THETA_PREV_RAW = THETA_RAW
  SQPH = DCMPLX(COS(0.5D0*THETA_UNWRAP),SIN(0.5D0*THETA_UNWRAP))
  GCORR(II) = GBASE(II)*SQPH
END DO
END SUBROUTINE CPU_APPLY_DET_PHASE_UNWRAP

SUBROUTINE CPU_SIMPSON_FROM_VECTOR(G,A0,B0,NIN,INTEGRAL)
IMPLICIT NONE
REAL(KIND=8), INTENT(IN) :: G(:), A0, B0
INTEGER(KIND=4), INTENT(IN) :: NIN
REAL(KIND=8), INTENT(OUT) :: INTEGRAL
INTEGER(KIND=4) :: NLOC, II
REAL(KIND=8) :: H, SLOCAL

NLOC = NIN
H = (B0-A0)/DBLE(NLOC)
IF (NLOC == 1) THEN
  INTEGRAL = 0.5D0*H*(G(1)+G(2))
ELSE IF ((NLOC/2)*2 == NLOC) THEN
  SLOCAL = 0.0D0
  DO II=2,NLOC-2,2
    SLOCAL = SLOCAL + 2.0D0*G(II+1) + 4.0D0*G(II+2)
  END DO
  INTEGRAL = (SLOCAL + G(1) + G(NLOC+1) + 4.0D0*G(2))*H/3.0D0
ELSE
  INTEGRAL = 0.0D0
  IF (NLOC > 3) THEN
    SLOCAL = 0.0D0
    DO II=2,NLOC-4,2
      SLOCAL = SLOCAL + 2.0D0*G(II+1) + 4.0D0*G(II+2)
    END DO
    INTEGRAL = (SLOCAL + G(1) + G(NLOC-2) + 4.0D0*G(2))*H/3.0D0
  END IF
  INTEGRAL = INTEGRAL + 3.0D0*H/8.0D0*(G(NLOC-2)+3.0D0*G(NLOC-1)+3.0D0*G(NLOC)+G(NLOC+1))
END IF
END SUBROUTINE CPU_SIMPSON_FROM_VECTOR

SUBROUTINE GET_G_TIME_CORR_IC13_PARTS(T,G_BASE,PHASE_RATIO,IERR)
IMPLICIT NONE
REAL(KIND=8), INTENT(IN) :: T
COMPLEX(KIND=8), INTENT(OUT) :: G_BASE, PHASE_RATIO
INTEGER(KIND=4), INTENT(OUT) :: IERR
INTEGER(KIND=4) :: II
COMPLEX(KIND=8) :: WORK01(N_VIB,N_VIB), WORK02(N_VIB,N_VIB), WORK03(N_VIB,N_VIB), WORK2(N_VIB,N_VIB)
COMPLEX(KIND=8) :: WORK3(1,1), WORK5(1,1)
COMPLEX(KIND=8) :: DET01, DET02, DET03, PH01, PH02, PH03
COMPLEX(KIND=8) :: LDET01, LDET02, LDET03, LDRATIO
REAL(KIND=8) :: ABS01, ABS02, ABS03, LOGHALF, MAGP, SCALE_DET

IERR = 0
G_BASE = DCMPLX(0.0D0,0.0D0)
PHASE_RATIO = DCMPLX(1.0D0,0.0D0)
S1=0
S2=0
B1=0
B2=0
WORK01=0
WORK02=0
WORK03=0

DO II=1,N_VIB,1
  S1(II,II)=SINH((BE-IMG*T)*EV_INI(II))
  S2(II,II)=SINH(IMG*EV_FINAL(II)*T)
  B1(II,II)=TANH((BE-IMG*T)*EV_INI(II)/2.0D0)
  B2(II,II)=TANH(IMG*EV_FINAL(II)*T/2.0D0)
END DO

DO II=1,N_VIB,1
  WORK01(II,II)=OMEGA1(II,II)*OMEGA2(II,II)/S1(II,II)/S2(II,II)/Z(II,1)/Z(II,1)
END DO
WORK02=MATMUL(MATMUL(MATMUL(TRANSPOSE(J),OMEGA2),B2),J)+MATMUL(OMEGA1,B1)
WORK03=MATMUL(MATMUL(MATMUL(TRANSPOSE(J),OMEGA2),CINV(B2)),J)+MATMUL(OMEGA1,CINV(B1))

LDET01 = CLOGDET(WORK01)
LDET02 = CLOGDET(WORK02)
LDET03 = CLOGDET(WORK03)
LDRATIO = LDET01 - LDET02 - LDET03
IF (REAL(LDRATIO) /= REAL(LDRATIO) .OR. AIMAG(LDRATIO) /= AIMAG(LDRATIO)) THEN
  IERR = -1320
  RETURN
END IF
LOGHALF = 0.5D0*REAL(LDRATIO)
PHASE_RATIO = DCMPLX(COS(AIMAG(LDRATIO)),SIN(AIMAG(LDRATIO)))
MAGP = ABS(PHASE_RATIO)
IF (MAGP /= MAGP .OR. MAGP == 0.0D0) THEN
  IERR = -1322
  RETURN
END IF
PHASE_RATIO = PHASE_RATIO/MAGP
WORK2=CINV(WORK02)
WORK3=EXP(MATMUL(MATMUL(TRANSPOSE(D),&
  & (MATMUL(MATMUL(MATMUL(MATMUL(MATMUL(MATMUL(OMEGA2,B2),J),WORK2),TRANSPOSE(J)),&
  & OMEGA2),B2)-MATMUL(OMEGA2,B2))),D)) * EXP(IMG*T*DE)
WORK5=MATMUL(MATMUL(MATMUL(MATMUL(MATMUL(MATMUL(MATMUL(MATMUL(MATMUL( &
  & MATMUL(MATMUL(MATMUL(MATMUL(MATMUL( &
  & TRANSPOSE(D),OMEGA2),B2),J), &
  & TRANSPOSE(WORK2)),OMEGA1),B1),F),OMEGA1),B1),WORK2), &
  & TRANSPOSE(J)),OMEGA2),B2),D) &
  & +0.5D0*CTRA(MATMUL(F,CINV(MATMUL( &
  & MATMUL(MATMUL(TRANSPOSE(J),CINV(OMEGA2)),B2),J)+ &
  & MATMUL(CINV(OMEGA1),B1))))  &
  & -0.5D0*CTRA(MATMUL(F,CINV(MATMUL( &
  & MATMUL(MATMUL(TRANSPOSE(J),CINV(OMEGA2)),CINV(B2)),J)+ &
  & MATMUL(CINV(OMEGA1),CINV(B1)))))
IF (LOGHALF > LOG(HUGE(1.0D0))) THEN
  IERR = -1323
  RETURN
ELSE IF (LOGHALF < LOG(TINY(1.0D0))) THEN
  SCALE_DET = 0.0D0
ELSE
  SCALE_DET = DEXP(LOGHALF)
END IF
G_BASE = SCALE_DET*WORK3(1,1)*WORK5(1,1)
END SUBROUTINE GET_G_TIME_CORR_IC13_PARTS

END SUBROUTINE TIME_CORRELATION_IC
