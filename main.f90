PROGRAM MAIN
IMPLICIT NONE
INTEGER(KIND=4) :: SUB,NARG,N_ATOMS,INTEGRAL_STEPS
INTEGER(KIND=4) :: SOC_DERIV_MODE,NAC_MODE,NAC_MODE_FOR_NASVC
INTEGER(KIND=4) :: NUM_STATES_SAME_SPIN_INIT,NUM_STATES_SAME_SPIN_FINAL
INTEGER(KIND=4) :: TARGET_INIT,TARGET_FINAL,NUM_ZERO_HUANG_MODE
INTEGER(KIND=4) :: ZERO_HUANG_FACTOR_MODES(1000)
INTEGER(KIND=4),PARAMETER :: LOGID=11
COMPLEX(KIND=8) :: ISC_SOC
REAL(KIND=8) :: TEMP,ENERGY_1,ENERGY_2,LAMBDA_SUR,LAMBDA_SUR2
REAL(KIND=8) :: TIME_STEP,DAMPING_WIDTH
CHARACTER*200 :: INPUT_FILE_NAME,OUTPUT_FILE_NAME
CHARACTER*200 :: INIT_FILENAME,FINAL_FILENAME,HESSIAN_FILE_1,HESSIAN_FILE_2
CHARACTER*200 :: NAC_FILE,FN_SOC_DERIV
CHARACTER*200 :: FN_NAC_SPIN_INIT,FN_NAC_SPIN_FINAL
CHARACTER*200 :: FN_ENE_SPIN_INIT,FN_ENE_SPIN_FINAL
CHARACTER*200 :: FN_SOC_INIT_FINALS,FN_SOC_FINAL_INITS
CHARACTER*200 :: FN_SOC_DERIV_INIT_FINALS,FN_SOC_DERIV_FINAL_INITS
LOGICAL :: CAL_REO,CRYSTAL,USE_DAMPING_FUNCTION,USER_SPECIFIED_OUT_NAME
LOGICAL :: USE_DUSCHINSKY,USE_HT,USE_NASVC,SIMPLIFIED_SVC
CHARACTER*8 :: START_DATE,END_DATE
CHARACTER*10 :: START_TIME,END_TIME
INTEGER(KIND=8) :: START_COUNT,END_COUNT,COUNT_RATE
REAL(KIND=8) :: ELAPSED_TIME

CALL DATE_AND_TIME(START_DATE,START_TIME)
CALL SYSTEM_CLOCK(START_COUNT,COUNT_RATE)
WRITE(*,*) 'PROGRAM START TIME: ',START_DATE,' ',START_TIME

NARG=COMMAND_ARGUMENT_COUNT()
IF (NARG < 1 .OR. NARG > 2) THEN
  WRITE(*,*) 'Usage: RC_Kit_CPU.exe/RC_Kit_GPU.exe INPUT [OUTPUT]'
  STOP 200
END IF
CALL GET_COMMAND_ARGUMENT(1,INPUT_FILE_NAME)
USER_SPECIFIED_OUT_NAME=(NARG == 2)
IF (USER_SPECIFIED_OUT_NAME) CALL GET_COMMAND_ARGUMENT(2,OUTPUT_FILE_NAME)

CALL READ_DATA(INPUT_FILE_NAME,SUB,ISC_SOC,TEMP,ENERGY_1,&
  ENERGY_2,LAMBDA_SUR,LAMBDA_SUR2,N_ATOMS,CAL_REO,&
  CRYSTAL,INIT_FILENAME,FINAL_FILENAME,HESSIAN_FILE_1,HESSIAN_FILE_2,&
  NAC_FILE,NAC_MODE,LOGID,INTEGRAL_STEPS,TIME_STEP,&
  USE_DAMPING_FUNCTION,DAMPING_WIDTH,USE_DUSCHINSKY,USE_HT,USE_NASVC,&
  SIMPLIFIED_SVC,FN_SOC_DERIV,SOC_DERIV_MODE,NUM_STATES_SAME_SPIN_INIT,NUM_STATES_SAME_SPIN_FINAL,&
  FN_NAC_SPIN_INIT,FN_NAC_SPIN_FINAL,FN_ENE_SPIN_INIT,FN_ENE_SPIN_FINAL,TARGET_INIT,&
  TARGET_FINAL,FN_SOC_INIT_FINALS,FN_SOC_FINAL_INITS,NAC_MODE_FOR_NASVC,FN_SOC_DERIV_INIT_FINALS,&
  FN_SOC_DERIV_FINAL_INITS,NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES)

IF (SUB == 5) THEN
  CALL TIME_CORRELATION_ISC(ISC_SOC,TEMP,ENERGY_1,ENERGY_2,LAMBDA_SUR,LAMBDA_SUR2,N_ATOMS,CAL_REO,CRYSTAL,&
    INIT_FILENAME,FINAL_FILENAME,HESSIAN_FILE_1,HESSIAN_FILE_2,LOGID,&
    INTEGRAL_STEPS,TIME_STEP,SUB,USE_DAMPING_FUNCTION,DAMPING_WIDTH,&
    OUTPUT_FILE_NAME,USER_SPECIFIED_OUT_NAME,USE_DUSCHINSKY,USE_HT,USE_NASVC,SIMPLIFIED_SVC,&
    FN_SOC_DERIV,SOC_DERIV_MODE,NUM_STATES_SAME_SPIN_INIT,NUM_STATES_SAME_SPIN_FINAL,&
    FN_NAC_SPIN_INIT,FN_NAC_SPIN_FINAL,FN_ENE_SPIN_INIT,FN_ENE_SPIN_FINAL,TARGET_INIT,TARGET_FINAL,&
    FN_SOC_INIT_FINALS,FN_SOC_FINAL_INITS,NAC_MODE_FOR_NASVC,&
    FN_SOC_DERIV_INIT_FINALS,FN_SOC_DERIV_FINAL_INITS,NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES)
ELSE IF (SUB == 13) THEN
  CALL TIME_CORRELATION_IC(NAC_FILE,NAC_MODE,TEMP,ENERGY_1,ENERGY_2,LAMBDA_SUR,LAMBDA_SUR2,&
    N_ATOMS,CAL_REO,CRYSTAL,INIT_FILENAME,FINAL_FILENAME,HESSIAN_FILE_1,HESSIAN_FILE_2,LOGID,&
    INTEGRAL_STEPS,TIME_STEP,SUB,USE_DAMPING_FUNCTION,DAMPING_WIDTH,&
    OUTPUT_FILE_NAME,USER_SPECIFIED_OUT_NAME,USE_DUSCHINSKY,NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES)
END IF

CALL SYSTEM_CLOCK(END_COUNT)
CALL DATE_AND_TIME(END_DATE,END_TIME)
ELAPSED_TIME=DBLE(END_COUNT-START_COUNT)/DBLE(COUNT_RATE)
WRITE(*,*) 'PROGRAM END TIME:   ',END_DATE,' ',END_TIME
WRITE(*,*) 'TOTAL ELAPSED TIME: ',ELAPSED_TIME,' s'
END PROGRAM
