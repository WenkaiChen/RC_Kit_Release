      EV_FINAL(I-COUNT_ZERO_MODE)=DCMPLX(FINAL_FREQ(I)*2*PI,0.D0)
      Z(I-COUNT_ZERO_MODE,1)=0
      D(I-COUNT_ZERO_MODE,1)=DCMPLX(DELTA_Q2(I),0.D0)
      IF (USE_HT) THEN
        COUP_DER_VIB(I-COUNT_ZERO_MODE,1) = COUP_DER_NM(I)
      END IF
      IF (USE_NASVC) THEN
        NAC_SVC_TOTAL_VIB(I-COUNT_ZERO_MODE) = NAC_SVC_TOTAL_NM(I)
        IF (USE_FULL_SVC) THEN
          V_DSO_NA_VIB(I-COUNT_ZERO_MODE) = V_DSO_NA_NM(I)
          DO K=1, NUM_STATES_SAME_SPIN_FINAL-1, 1
            SOC_DERIV_INIT_FINALS_VIB(K,I-COUNT_ZERO_MODE) = SOC_DERIV_INIT_FINALS_NM(K,I)
          END DO
          DO K=1, NUM_STATES_SAME_SPIN_INIT-1, 1
