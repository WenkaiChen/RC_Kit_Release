      H_VECTOR=COUP_DER_VIB
      M_DAGGER=TRANSPOSE(CONJG(M_HT_NA_VIB))
      G1_PLUS_MATRIX=0.5D0*(L1_A1_INV+L2_A2_INV) &
        & -MATMUL(W_VECTOR,TRANSPOSE(A1_INV_A3))

      G_1_2=0
      DO II=1,N_VIB,1
        DO KK=1,N_VIB,1
          G_1_2=G_1_2-(CONJG(SOC_COMPLEX)*M_HT_NA_VIB(II,KK)) &
            & *G1_PLUS_MATRIX(II,KK)
        END DO
      END DO
      G_1_2=G_1_2*GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)
      G_1_3=(CONJG(SOC_COMPLEX)*S_HT_NA) &
        & *GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)
      G_1_5=0
      DO II=1,N_VIB,1
        DO KK=1,N_VIB,1
          DO LL=1,N_VIB,1
            G_1_5=G_1_5-(CONJG(H_VECTOR(LL,1))*M_HT_NA_VIB(KK,II)) &
              & *(A1_INV_A3(II,1)*W_VECTOR(KK,1)*A1_INV_A3(LL,1) &
              & +0.5D0*(A1_INV(II,LL)-A2_INV(II,LL))*W_VECTOR(KK,1) &
              & -0.5D0*A1_INV_A3(II,1)*(L1_A1_INV(KK,LL)-L2_A2_INV(KK,LL)) &
              & -0.5D0*A1_INV_A3(LL,1)*(L1_A1_INV(KK,II)+L2_A2_INV(KK,II)))
          END DO
        END DO
      END DO
      G_1_5=G_1_5*GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)
      G_1_6=0
      DO II=1,N_VIB,1
        G_1_6=G_1_6-(CONJG(H_VECTOR(II,1))*S_HT_NA)*A1_INV_A3(II,1)
      END DO
      G_1_6=G_1_6*GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)

      G_2_3=CONJG(S_HT_NA)*S_HT_NA &
        & *GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)
      M_P0=W_VECTOR
      M_QP0=G1_PLUS_MATRIX
      G_2_5=0
      DO II=1,N_VIB,1
        G_2_5=G_2_5-(CONJG(V_DSO_NA_VIB(II))*S_HT_NA)*M_P0(II,1)
      END DO
      G_2_5=G_2_5*GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)
      G_2_6=0
      DO II=1,N_VIB,1
        DO KK=1,N_VIB,1
          G_2_6=G_2_6-(M_DAGGER(II,KK)*S_HT_NA)*M_QP0(KK,II)
        END DO
      END DO
      G_2_6=G_2_6*GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)

      WORK6=MATMUL(M_HT_NA_VIB,A1_INV_A3)
      TEMP_VECTOR=MATMUL(M_PP,WORK6)
      G_2_4=-SUM(CONJG(V_DSO_NA_VIB)*TEMP_VECTOR(:,1))
      G_2_4=G_2_4+0.5D0*SUM(CONJG(V_DSO_NA_VIB)*W_VECTOR(:,1)) &
        & *SUM(M_HT_NA_VIB*(L1_A1_INV+L2_A2_INV))
      WORK6=MATMUL(TRANSPOSE(M_HT_NA_VIB),W_VECTOR)
      TEMP_VECTOR=MATMUL(L1_A1_INV-L2_A2_INV,WORK6)
      G_2_4=G_2_4+0.5D0*SUM(CONJG(V_DSO_NA_VIB)*TEMP_VECTOR(:,1))
      G_2_4=G_2_4*GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)

      IF (DIRECTION == 1) THEN
        G_1_4_MATRIX=-MATMUL(L1_A1_INV,MATMUL(OMEGA1,B1)) &
          & +MATMUL(L2_A2_INV,MATMUL(OMEGA1,CINV(B1)))
        WORK01=MATMUL(W_VECTOR,TRANSPOSE(A1_INV_A3))
        SUM1=SUM(CONJG(M_HT_NA_VIB)*WORK01)
        SUM2=SUM(M_HT_NA_VIB*WORK01)
        SUM3=SUM(CONJG(M_HT_NA_VIB)*(L1_A1_INV+L2_A2_INV))
        SUM4=SUM(M_HT_NA_VIB*(L1_A1_INV+L2_A2_INV))
        MQPQP_VALUE=16.D0*SUM1*SUM2-8.D0*SUM3*SUM2 &
          & -8.D0*SUM1*SUM4+4.D0*SUM3*SUM4

        WORK6=MATMUL(TRANSPOSE(CONJG(M_HT_NA_VIB)),W_VECTOR)
        WORK7=MATMUL(TRANSPOSE(M_HT_NA_VIB),W_VECTOR)
        TEMP_VECTOR=MATMUL(A1_INV-A2_INV,WORK7)
        MQPQP_VALUE=MQPQP_VALUE+8.D0*SUM(WORK6(:,1)*TEMP_VECTOR(:,1))

        TEMP_VECTOR=MATMUL(M_HT_NA_VIB,A1_INV_A3)
        M_P0=MATMUL(TRANSPOSE(L1_A1_INV-L2_A2_INV),TEMP_VECTOR)
        MQPQP_VALUE=MQPQP_VALUE-8.D0*SUM(WORK6(:,1)*M_P0(:,1))

        WORK6=MATMUL(CONJG(M_HT_NA_VIB),A1_INV_A3)
        TEMP_VECTOR=MATMUL(L1_A1_INV-L2_A2_INV,WORK7)
        MQPQP_VALUE=MQPQP_VALUE-8.D0*SUM(WORK6(:,1)*TEMP_VECTOR(:,1))

        WORK7=MATMUL(M_HT_NA_VIB,A1_INV_A3)
        TEMP_VECTOR=MATMUL(G_1_4_MATRIX,WORK7)
        MQPQP_VALUE=MQPQP_VALUE+8.D0*SUM(WORK6(:,1)*TEMP_VECTOR(:,1))

        WORK01=MATMUL(MATMUL(G_1_4_MATRIX,M_HT_NA_VIB),A1_INV-A2_INV)
        MQPQP_VALUE=MQPQP_VALUE+4.D0*SUM(CONJG(M_HT_NA_VIB)*WORK01)

        WORK01=MATMUL(M_HT_NA_VIB,TRANSPOSE(L1_A1_INV-L2_A2_INV))
        WORK02=MATMUL(CONJG(M_HT_NA_VIB),TRANSPOSE(L1_A1_INV-L2_A2_INV))
        MQPQP_VALUE=MQPQP_VALUE+4.D0*CTRA(MATMUL(WORK01,WORK02))
        G_2_2=0.0625D0*MQPQP_VALUE
        G_2_2=G_2_2*GAUSSIAN_PREFACTOR*GAUSSIAN_EXPONENT(1,1)
      END IF
    END IF
  END IF
  IF (N_DIRECTION == 2) THEN
    IF (DIRECTION == 1) THEN
      G_POS=[G_0_0,G_0_1,G_0_2,G_1_1,G_1_2,G_1_3,G_1_4,G_1_5,G_1_6, &
        G_2_1,G_2_2,G_2_3,G_2_4,G_2_5,G_2_6]
    ELSE
      G_NEG=[G_0_0,G_0_1,G_0_2,G_1_1,G_1_2,G_1_3,G_1_4,G_1_5,G_1_6, &
        G_2_1,G_2_2,G_2_3,G_2_4,G_2_5,G_2_6]
      B1=CONJG(B1)
      B2=CONJG(B2)
      G_0_0=G_POS(1)
      G_0_1=G_POS(2)
      G_0_2=G_POS(3)
      G_1_1=G_POS(4)
      G_1_2=G_POS(5)
      G_1_3=G_POS(6)
      G_1_4=G_POS(7)
      G_1_5=G_POS(8)
      G_1_6=G_POS(9)
      G_2_1=G_POS(10)
      G_2_2=G_POS(11)
      G_2_3=G_POS(12)
      G_2_4=G_POS(13)
      G_2_5=G_POS(14)
      G_2_6=G_POS(15)
    END IF
  END IF
END DO

G_FINAL=ABS(SOC_COMPLEX)**2*REAL(G_0_0)
IF (USE_FULL_SVC) THEN
  G_FINAL=ABS(SOC_COMPLEX)**2*REAL(G_0_0)
  IF (USE_HT) G_FINAL = G_FINAL + 2.D0*REAL(G_0_1) + REAL(G_0_2)
  IF (USE_NASVC) G_FINAL = G_FINAL + 2.D0*REAL(G_1_1) + REAL(G_2_1)
  IF (USE_HT .AND. USE_NASVC) G_FINAL = G_FINAL &
    & +2.D0*REAL(G_1_2+G_1_3+G_1_4+G_1_5+G_1_6) &
    & +REAL(G_2_2+G_2_3) + 2.D0*REAL(G_2_4+G_2_5+G_2_6)
ELSE IF ((USE_HT .AND. .NOT. (USE_NASVC))) THEN
  G_FINAL=ABS(SOC_COMPLEX)**2*REAL(G_0_0) + 2.D0*REAL(G_0_1) + REAL(G_0_2)
ELSE IF ((USE_NASVC .AND. .NOT. (USE_HT))) THEN
  G_FINAL=ABS(SOC_COMPLEX)**2*REAL(G_0_0) + 2.D0*REAL(G_1_1) + REAL(G_2_1)
ELSE IF ((USE_HT .AND. USE_NASVC)) THEN
  G_FINAL=ABS(SOC_COMPLEX)**2*REAL(G_0_0) + 2.D0*REAL(G_0_1) + REAL(G_0_2) &
    & +REAL(G_2_1) + 2.D0*REAL(G_1_1+G_1_4)
END IF
IF (DET_UNWRAP_MODE) RETURN
IF (USE_DAMPING_FUNCTION) THEN
  WIN=GAUSS(T,0.0D0,1.0D0/DAMPING_WIDTH*3.335653E-12/AUT2S)

  G_FINAL = WIN*G_FINAL
END IF

IF (T > TIME_STEP*1.5D-12/AUT2S-1.0D-38) THEN
  IF (USE_DAMPING_FUNCTION) THEN
    IF (USE_FULL_SVC) THEN
      IF (USE_HT .AND. USE_NASVC) THEN
        write(23333,"(F12.5,17(1PE20.10))") T*2.418884326505D-2, G_FINAL, &
          REAL(G_0_0), REAL(G_0_1), REAL(G_0_2), &
          REAL(G_1_1), REAL(G_1_2), REAL(G_1_3), &
          REAL(G_1_4), REAL(G_1_5), REAL(G_1_6), &
          REAL(G_2_1), REAL(G_2_2), REAL(G_2_3), &
          REAL(G_2_4), REAL(G_2_5), REAL(G_2_6), WIN
      ELSE IF (USE_HT) THEN
        write(23333,"(F12.5,5(1PE20.10))") T*2.418884326505D-2, G_FINAL, &
          REAL(G_0_0), REAL(G_0_1), REAL(G_0_2), WIN
      ELSE IF (USE_NASVC) THEN
        write(23333,"(F12.5,5(1PE20.10))") T*2.418884326505D-2, G_FINAL, &
          REAL(G_0_0), REAL(G_1_1), REAL(G_2_1), WIN
      ELSE
        write(23333,"(F12.5,2(1PE20.10))") T*2.418884326505D-2, G_FINAL, WIN
      END IF
    ELSE IF ((USE_HT .AND. .NOT. (USE_NASVC))) THEN
      write(23333,"(F12.5,5(1PE20.10))") T*2.418884326505D-2, G_FINAL, REAL(G_0_0), REAL(G_0_1), REAL(G_0_2), WIN
    ELSE IF ((USE_NASVC .AND. .NOT. (USE_HT))) THEN
      write(23333,"(F12.5,5(1PE20.10))") T*2.418884326505D-2, G_FINAL, REAL(G_0_0), REAL(G_1_1), REAL(G_2_1), WIN
    ELSE IF ((USE_HT .AND. USE_NASVC)) THEN
      write(23333,"(F12.5,8(1PE20.10))") T*2.418884326505D-2, G_FINAL, REAL(G_0_0), REAL(G_0_1), REAL(G_0_2), REAL(G_1_1), REAL(G_1_4), REAL(G_2_1), WIN
    ELSE
      write(23333,"(F12.5,2(1PE20.10))") T*2.418884326505D-2, G_FINAL, WIN
    END IF
  ELSE
    IF (USE_FULL_SVC) THEN
      IF (USE_HT .AND. USE_NASVC) THEN
        write(23333,"(F12.5,16(1PE20.10))") T*2.418884326505D-2, G_FINAL, &
          REAL(G_0_0), REAL(G_0_1), REAL(G_0_2), &
          REAL(G_1_1), REAL(G_1_2), REAL(G_1_3), &
          REAL(G_1_4), REAL(G_1_5), REAL(G_1_6), &
          REAL(G_2_1), REAL(G_2_2), REAL(G_2_3), &
          REAL(G_2_4), REAL(G_2_5), REAL(G_2_6)
      ELSE IF (USE_HT) THEN
        write(23333,"(F12.5,4(1PE20.10))") T*2.418884326505D-2, G_FINAL, &
          REAL(G_0_0), REAL(G_0_1), REAL(G_0_2)
      ELSE IF (USE_NASVC) THEN
        write(23333,"(F12.5,4(1PE20.10))") T*2.418884326505D-2, G_FINAL, &
          REAL(G_0_0), REAL(G_1_1), REAL(G_2_1)
      ELSE
        write(23333,"(F12.5,1PE20.10)") T*2.418884326505D-2, G_FINAL
      END IF
    ELSE IF ((USE_HT .AND. .NOT. (USE_NASVC))) THEN
      write(23333,"(F12.5,4(1PE20.10))") T*2.418884326505D-2, G_FINAL, REAL(G_0_0), REAL(G_0_1), REAL(G_0_2)
    ELSE IF ((USE_NASVC .AND. .NOT. (USE_HT))) THEN
      write(23333,"(F12.5,4(1PE20.10))") T*2.418884326505D-2, G_FINAL, REAL(G_0_0), REAL(G_1_1), REAL(G_2_1)
    ELSE IF ((USE_HT .AND. USE_NASVC)) THEN
      write(23333,"(F12.5,7(1PE20.10))") T*2.418884326505D-2, G_FINAL, REAL(G_0_0), REAL(G_0_1), REAL(G_0_2), REAL(G_1_1), REAL(G_1_4), REAL(G_2_1)
    ELSE
      write(23333,"(F12.5,1PE20.10)") T*2.418884326505D-2, G_FINAL
    END IF
  END IF
END IF
