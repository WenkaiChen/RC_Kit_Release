  IF (USE_DUSCHINSKY) DELTA_Q2=MATMUL(TRANSPOSE(DUSHIN_MAT),DELTA_Q1)

  CALL HUANG_FACTOR(N_MODE,INIT_FREQ,DELTA_Q1,HUANG_RHYS_1,HUANG_RHYS_1_I,HUANG_RHYS_1_EFF,FREQ1_EFF,SIGMA)

  COUNT_ZERO_MODE = 0
  LOOP_NVIB1: DO I=1,N_VIB+NUM_ZERO_HUANG_MODE,1
    IF ((I==ZERO_HUANG_FACTOR_MODES(COUNT_ZERO_MODE + 1)) .AND. (NUM_ZERO_HUANG_MODE>0)) THEN
      COUNT_ZERO_MODE = COUNT_ZERO_MODE + 1
      CYCLE LOOP_NVIB1
    END IF

    IF ( .NOT. CRYSTAL ) THEN
      OMEGA1(I-COUNT_ZERO_MODE,I-COUNT_ZERO_MODE)=DCMPLX(INIT_FREQ(I+6)*2*PI,0.D0)
      OMEGA2(I-COUNT_ZERO_MODE,I-COUNT_ZERO_MODE)=DCMPLX(FINAL_FREQ(I+6)*2*PI,0.D0)
      EV_INI(I-COUNT_ZERO_MODE) = DCMPLX(INIT_FREQ(I+6)*2*PI,0.D0)
      EV_FINAL(I-COUNT_ZERO_MODE)=DCMPLX(FINAL_FREQ(I+6)*2*PI,0.D0)
      Z(I-COUNT_ZERO_MODE,1)=0
      D(I-COUNT_ZERO_MODE,1)=DCMPLX(DELTA_Q2(I+6),0.D0)
      IF (USE_HT) THEN
        COUP_DER_VIB(I-COUNT_ZERO_MODE,1) = COUP_DER_NM(I+6)
      END IF
      IF (USE_NASVC) THEN
        NAC_SVC_TOTAL_VIB(I-COUNT_ZERO_MODE) = NAC_SVC_TOTAL_NM(I+6)
        IF (USE_FULL_SVC) THEN
          V_DSO_NA_VIB(I-COUNT_ZERO_MODE) = V_DSO_NA_NM(I+6)
          DO K=1, NUM_STATES_SAME_SPIN_FINAL-1, 1
            SOC_DERIV_INIT_FINALS_VIB(K,I-COUNT_ZERO_MODE) = SOC_DERIV_INIT_FINALS_NM(K,I+6)
          END DO
          DO K=1, NUM_STATES_SAME_SPIN_INIT-1, 1
            SOC_DERIV_FINAL_INITS_VIB(K,I-COUNT_ZERO_MODE) = SOC_DERIV_FINAL_INITS_NM(K,I+6)
          END DO
        END IF
      END IF
      IF (USE_DUSCHINSKY) THEN
        COUNT_ZERO_MODE2 = 0
        LOOP_NVIB2: DO K=1,N_VIB+NUM_ZERO_HUANG_MODE,1
          IF ((K==ZERO_HUANG_FACTOR_MODES(COUNT_ZERO_MODE2 + 1)) .AND. (NUM_ZERO_HUANG_MODE>0)) THEN
            COUNT_ZERO_MODE2 = COUNT_ZERO_MODE2 + 1
            CYCLE LOOP_NVIB2
          END IF
          J(I-COUNT_ZERO_MODE,K-COUNT_ZERO_MODE2) = DUSHIN_MAT(I+6,K+6)
