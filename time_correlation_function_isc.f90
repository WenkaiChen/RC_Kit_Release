  END IF
  IF (USE_NASVC) THEN
    DO I=1,N_VIB,1
      DO K=1,N_VIB,1
        F_NA_NA(I,K)=CONJG(NAC_SVC_TOTAL_VIB(I))*NAC_SVC_TOTAL_VIB(K)
      END DO
    END DO
  ELSE
    F_NA_NA=0
  END IF
  IF (USE_HT .AND. USE_NASVC) THEN
    DO I=1,N_VIB,1
      DO K=1,N_VIB,1
        F_HT_NA(I,K)=CONJG(NAC_SVC_TOTAL_VIB(I))*COUP_DER_VIB(K,1)
