          END DO
        END IF
      END IF
    END IF

    LOOP: DO K=1,1000
      TMP_VALUE=EXP(-(REAL(EV_INI(I))*(K-0.5))*BE)
      IF (TMP_VALUE > 1.0D-15 .OR. (K .LE. 20)) THEN
        Z(I-COUNT_ZERO_MODE,1)=Z(I-COUNT_ZERO_MODE,1) + DCMPLX(TMP_VALUE,0.D0)
      ELSE
        EXIT LOOP
      END IF
    END DO LOOP
  END DO LOOP_NVIB1
  J=TRANSPOSE(J)

  COUNT_ZERO_MODE = 0
  IF (USE_HT) THEN
    LOOP_NVIB4: DO I=1,N_VIB,1
      LOOP_NVIB5: DO K=1,N_VIB,1
        F_HT_HT(I,K)=CONJG(COUP_DER_VIB(I,1))*COUP_DER_VIB(K,1)
      END DO LOOP_NVIB5
