SUBROUTINE APPLY_DET_PHASE_UNWRAP_CPU(GBASE, PHASE_RATIO, GCORR, NPTS)
IMPLICIT NONE
INTEGER(KIND=4), INTENT(IN) :: NPTS
COMPLEX(KIND=8), INTENT(IN) :: GBASE(NPTS), PHASE_RATIO(NPTS)
COMPLEX(KIND=8), INTENT(OUT) :: GCORR(NPTS)
INTEGER(KIND=4) :: I
REAL(KIND=8) :: THETA_RAW, THETA_PREV, THETA_UNWRAPPED, DTHETA, MAGP
COMPLEX(KIND=8) :: HALF_PHASE

IF (NPTS <= 0) RETURN
THETA_PREV = 0.0D0
THETA_UNWRAPPED = 0.0D0
DO I=1,NPTS
  MAGP = ABS(PHASE_RATIO(I))
  IF (MAGP == 0.0D0 .OR. MAGP /= MAGP) THEN
    WRITE(LOGID,*) "ISC determinant phase is invalid at time index: ",I
    WRITE(*,*) "ISC determinant phase is invalid at time index: ",I
    STOP 202
  ELSE
    THETA_RAW = ATAN2(AIMAG(PHASE_RATIO(I)), REAL(PHASE_RATIO(I)))
    IF (I == 1) THEN
      THETA_UNWRAPPED = THETA_RAW
    ELSE
      DTHETA = THETA_RAW - THETA_PREV
      DO WHILE (DTHETA > PI)
        DTHETA = DTHETA - 2.0D0*PI
      END DO
      DO WHILE (DTHETA <= -PI)
        DTHETA = DTHETA + 2.0D0*PI
      END DO
      THETA_UNWRAPPED = THETA_UNWRAPPED + DTHETA
    END IF
    HALF_PHASE = DCMPLX(COS(0.5D0*THETA_UNWRAPPED),SIN(0.5D0*THETA_UNWRAPPED))
    GCORR(I) = GBASE(I)*HALF_PHASE
    THETA_PREV = THETA_RAW
  END IF
END DO
END SUBROUTINE APPLY_DET_PHASE_UNWRAP_CPU

