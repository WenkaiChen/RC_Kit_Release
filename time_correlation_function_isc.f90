SUBROUTINE TIME_CORRELATION_ISC(ISC_SOC,TEMP,ENERGY_1,ENERGY_2,LAMBDA_SUR,LAMBDA_SUR2,N_ATOMS,CAL_REO,CRYSTAL,&
  INIT_FILENAME,FINAL_FILENAME,HESSIAN_FILE_1,HESSIAN_FILE_2,LOGID,&
  INTEGRAL_STEPS,TIME_STEP,&
  SUB,USE_DAMPING_FUNCTION,DAMPING_WIDTH,&
  OUTPUT_FILE_NAME,USER_SPECIFIED_OUT_NAME,&
  USE_DUSCHINSKY,USE_HT,USE_NASVC,SIMPLIFIED_SVC,&
  FN_SOC_DERIV,SOC_DERIV_MODE,&
  NUM_STATES_SAME_SPIN_INIT, NUM_STATES_SAME_SPIN_FINAL,&
  FN_NAC_SPIN_INIT, FN_NAC_SPIN_FINAL, FN_ENE_SPIN_INIT,&
  FN_ENE_SPIN_FINAL, TARGET_INIT, TARGET_FINAL,&
  FN_SOC_INIT_FINALS, FN_SOC_FINAL_INITS, NAC_MODE_FOR_NASVC,&
  FN_SOC_DERIV_INIT_FINALS, FN_SOC_DERIV_FINAL_INITS,&
  NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES)

USE MATRIX_OPERATOR
USE GAUSS_FUNCITON
#ifdef USE_CUDA
USE CUDA_FASTPATH
#endif
IMPLICIT NONE

COMPLEX(KIND=8) :: ISC_SOC
REAL(KIND=8) :: TEMP
REAL(KIND=8) :: ENERGY_1,ENERGY_2
REAL(KIND=8) :: LAMBDA_SUR,LAMBDA_SUR2
REAL(KIND=8) :: DAMPING_WIDTH
INTEGER(KIND=4) :: INTEGRAL_STEPS
INTEGER(KIND=4) :: N_ATOMS
INTEGER(KIND=4) :: LOGID
INTEGER(KIND=4) :: NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES(1000)
INTEGER(KIND=4) :: SOC_DERIV_MODE, NAC_MODE_FOR_NASVC
INTEGER(KIND=4) :: NUM_STATES_SAME_SPIN_INIT, NUM_STATES_SAME_SPIN_FINAL
INTEGER(KIND=4) :: TARGET_INIT, TARGET_FINAL
CHARACTER*200 :: INIT_FILENAME
CHARACTER*200 :: FINAL_FILENAME
CHARACTER*200 :: HESSIAN_FILE_1
CHARACTER*200 :: HESSIAN_FILE_2
CHARACTER*200 :: FN_SOC_DERIV
CHARACTER*200 :: FN_NAC_SPIN_INIT
CHARACTER*200 :: FN_NAC_SPIN_FINAL
CHARACTER*200 :: FN_ENE_SPIN_INIT
CHARACTER*200 :: FN_ENE_SPIN_FINAL
CHARACTER*200 :: FN_SOC_INIT_FINALS
CHARACTER*200 :: FN_SOC_FINAL_INITS
CHARACTER*200 :: FN_SOC_DERIV_INIT_FINALS
CHARACTER*200 :: FN_SOC_DERIV_FINAL_INITS
LOGICAL :: CAL_REO
LOGICAL :: CRYSTAL
REAL(KIND=8) :: INTEGRAL_TIME,TIME_STEP
INTEGER(KIND=4) :: SUB
LOGICAL :: USE_DAMPING_FUNCTION
LOGICAL :: USER_SPECIFIED_OUT_NAME
LOGICAL :: USE_DUSCHINSKY
LOGICAL :: USE_HT
LOGICAL :: USE_NASVC
LOGICAL :: SIMPLIFIED_SVC
LOGICAL :: USE_FULL_SVC
LOGICAL :: STEP1_DONE, STEP2_DONE
CHARACTER*200 :: OUTPUT_FILE_NAME

INTEGER(KIND=4) :: N_MODE, N_VIB
REAL(KIND=8),ALLOCATABLE :: ATOM_MASS1(:),ATOM_MASS2(:)
REAL(KIND=8),ALLOCATABLE :: MASS_MAT1(:,:),MASS_MAT2(:,:)
REAL(KIND=8),ALLOCATABLE :: INIT_FREQ(:),FINAL_FREQ(:)
REAL(KIND=8),ALLOCATABLE :: INIT_L_MATRIX(:,:),FINAL_L_MATRIX(:,:)
REAL(KIND=8),ALLOCATABLE :: HUANG_RHYS_1_I(:),HUANG_RHYS_2_I(:)
REAL(KIND=8),ALLOCATABLE :: LAMBDA1_I(:),LAMBDA2_I(:)
REAL(KIND=8),ALLOCATABLE :: DELTA_Q1(:),DELTA_Q2(:)
REAL(KIND=8),ALLOCATABLE :: DUSHIN_MAT(:,:)
REAL(KIND=8) :: HUANG_RHYS_1,HUANG_RHYS_2
REAL(KIND=8) :: HUANG_RHYS_1_EFF,HUANG_RHYS_2_EFF
REAL(KIND=8) :: FREQ1_EFF,FREQ2_EFF
REAL(KIND=8) :: LAMBDA1_EFF,LAMBDA2_EFF
REAL(KIND=8) :: LAMBDA1_M,LAMBDA2_M
REAL(KIND=8) :: LAMBDA1_TOT,LAMBDA2_TOT
REAL(KIND=8) :: SIGMA
REAL(KIND=8) :: FACTOR_1,FACTOR_2,FACTOR_3
REAL(KIND=8) :: K_ISC
REAL(KIND=8) :: TMP_VALUE
INTEGER(KIND=4) :: I, K, L, COUNT_ZERO_MODE, COUNT_ZERO_MODE2
INTEGER(KIND=4) :: ROW_ID

REAL(KIND=8) :: BE
REAL(KIND=8) :: DE
COMPLEX(KIND=8),ALLOCATABLE :: EV_INI(:)
COMPLEX(KIND=8),ALLOCATABLE :: EV_FINAl(:)
COMPLEX(KIND=8),ALLOCATABLE :: OMEGA1(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: OMEGA2(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: S1(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: S2(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: B1(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: B2(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: Z(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: D(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: J(:,:)

COMPLEX(KIND=8),ALLOCATABLE :: COUP_DER_NM(:)
COMPLEX(KIND=8),ALLOCATABLE :: COUP_DER_VIB(:,:)
COMPLEX(KIND=8) :: SOC_COMPLEX

REAL(KIND=8),ALLOCATABLE :: NAC_SVC_INIT_NM(:,:), NAC_SVC_FINAL_NM(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: NAC_SVC_INIT_VIB(:,:,:), NAC_SVC_FINAL_VIB(:,:,:)
REAL(KIND=8),ALLOCATABLE :: NAC_MATRIX_SVC_NM(:)
COMPLEX(KIND=8),ALLOCATABLE :: NAC_SVC_TOTAL_NM(:)
COMPLEX(KIND=8),ALLOCATABLE :: NAC_SVC_TOTAL_VIB(:)
COMPLEX(KIND=8),ALLOCATABLE :: F_HT_HT(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: F_NA_NA(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: F_HT_NA(:,:)
REAL(KIND=8),ALLOCATABLE :: ENERGIES_FOR_NASVC_INIT(:), ENERGIES_FOR_NASVC_FINAL(:)
COMPLEX(KIND=8),ALLOCATABLE :: SOC_INIT_FINALS(:)
COMPLEX(KIND=8),ALLOCATABLE :: SOC_FINAL_INITS(:)
COMPLEX(KIND=8),ALLOCATABLE :: SOC_DERIV_INIT_FINALS_NM(:,:), SOC_DERIV_FINAL_INITS_NM(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: SOC_DERIV_INIT_FINALS_VIB(:,:), SOC_DERIV_FINAL_INITS_VIB(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: V_DSO_NA_NM(:), V_DSO_NA_VIB(:)
COMPLEX(KIND=8),ALLOCATABLE :: M_HT_NA_NM(:,:), M_HT_NA_VIB(:,:)
COMPLEX(KIND=8) :: S_DSO_NA, S_HT_NA

COMPLEX(KIND=8) :: G_0_0, G_0_1, G_0_2
COMPLEX(KIND=8) :: G_1_1, G_1_2, G_1_3, G_1_4, G_1_5, G_1_6
COMPLEX(KIND=8) :: G_2_1, G_2_2, G_2_3, G_2_4, G_2_5, G_2_6
COMPLEX(KIND=8) :: G_0_0_STEP1, G_0_1_STEP1, G_0_2_STEP1
COMPLEX(KIND=8) :: G_1_1_STEP1, G_1_2_STEP1, G_1_3_STEP1
COMPLEX(KIND=8) :: G_1_4_STEP1, G_1_5_STEP1, G_1_6_STEP1
COMPLEX(KIND=8) :: G_2_1_STEP1, G_2_2_STEP1, G_2_3_STEP1
COMPLEX(KIND=8) :: G_2_4_STEP1, G_2_5_STEP1, G_2_6_STEP1
COMPLEX(KIND=8) :: G_0_0_STEP2, G_0_1_STEP2, G_0_2_STEP2
COMPLEX(KIND=8) :: G_1_1_STEP2, G_1_2_STEP2, G_1_3_STEP2
COMPLEX(KIND=8) :: G_1_4_STEP2, G_1_5_STEP2, G_1_6_STEP2
COMPLEX(KIND=8) :: G_2_1_STEP2, G_2_2_STEP2, G_2_3_STEP2
COMPLEX(KIND=8) :: G_2_4_STEP2, G_2_5_STEP2, G_2_6_STEP2

REAL(KIND=8) :: ABSERR, ALIST, BLIST, RLIST, ELIST
INTEGER(KIND=4) :: NEVAL, IER, IORD, LAST
INTEGER(KIND=4) :: STEPS
REAL(KIND=8) :: THETA_01_DSO, THETA_02_DSO, THETA_00_DSO
REAL(KIND=8) :: THETA_01_D_HT, THETA_02_D_HT, THETA_00_D_HT
REAL(KIND=8) :: THETA_01_HT_HT, THETA_02_HT_HT, THETA_00_HT_HT
REAL(KIND=8) :: THETA_01_D_NA, THETA_02_D_NA, THETA_00_D_NA
REAL(KIND=8) :: THETA_01_NA_NA, THETA_02_NA_NA, THETA_00_NA_NA
REAL(KIND=8) :: THETA_01_HT_NA, THETA_02_HT_NA, THETA_00_HT_NA
LOGICAL :: DET_UNWRAP_MODE, SHARED_VIBRATIONAL_MATRICES
COMPLEX(KIND=8) :: G_NEG(15)
COMPLEX(KIND=8) :: DET_PHASE_RATIO_CUR
LOGICAL :: CUDA_DONE, CUDA_SHARED_VIB
INTEGER(KIND=4) :: CUDA_IERR, CUDA_STEPS_EFF, CUDA_NPTS
REAL(KIND=8),ALLOCATABLE :: CUDA_GOUT(:), CUDA_WIN(:)
COMPLEX(KIND=8),ALLOCATABLE :: CUDA_GPM(:,:,:)
REAL(KIND=8) :: CUDA_WEIGHTS(15)
LOGICAL :: CUDA_ACTIVE(15)
CHARACTER(LEN=5),PARAMETER :: CUDA_GNAMES(15) = (/ &
  "G_0_0","G_0_1","G_0_2","G_1_1","G_1_2","G_1_3","G_1_4","G_1_5", &
  "G_1_6","G_2_1","G_2_2","G_2_3","G_2_4","G_2_5","G_2_6" /)

REAL(KIND=8) :: INTE
REAL(KIND=8) :: FC
REAL(KIND=8) :: RC
REAL(KIND=8) :: ITSA
REAL(KIND=8) :: ITSE, TEST

REAL(KIND=8),PARAMETER :: HBAR=1.054571800D-34
REAL(KIND=8),PARAMETER :: PI=3.1415926535897932384
REAL(KIND=8),PARAMETER :: K_B=1.38064852D-23
REAL(KIND=8),PARAMETER :: AMU2KG=1.66053878D-27
REAL(KIND=8),PARAMETER :: B2M=0.529177249D-10
REAL(KIND=8),PARAMETER :: AU2J=4.35974434D-18
REAL(KIND=8),PARAMETER :: AUT2S=2.418884254E-17
COMPLEX(KIND=8) :: IMG=DCMPLX(0.0D0,1.0D0)
REAL(KIND=8) :: Pa, Pe
REAL(KIND=8),PARAMETER :: CLIGHT=2.998D10

USE_FULL_SVC = (SUB == 5 .AND. (.NOT. SIMPLIFIED_SVC))

IF (.NOT. USER_SPECIFIED_OUT_NAME) THEN
  OPEN(LOGID,FILE="TIME_CORRELATION_ISC.TXT",STATUS="REPLACE")
  OPEN(23333,FILE="TIME_CORRELATION_ISC_TC.TXT",STATUS="REPLACE")
ELSE
  OPEN(LOGID,FILE=OUTPUT_FILE_NAME,STATUS="REPLACE")
  OPEN(23333,FILE=TRIM(OUTPUT_FILE_NAME) // "_TC.TXT",STATUS="REPLACE")
END IF

N_MODE=3*N_ATOMS
IF ( .NOT. CRYSTAL ) THEN
  N_VIB = N_MODE-6 - NUM_ZERO_HUANG_MODE
ELSE
  N_VIB = N_MODE - NUM_ZERO_HUANG_MODE
END IF
ALLOCATE(ATOM_MASS1(N_ATOMS),ATOM_MASS2(N_ATOMS))
ALLOCATE(MASS_MAT1(N_MODE,N_MODE))
ALLOCATE(MASS_MAT2(N_MODE,N_MODE))
ALLOCATE(INIT_FREQ(N_MODE),FINAL_FREQ(N_MODE))
ALLOCATE(INIT_L_MATRIX(N_MODE,N_MODE))
ALLOCATE(FINAL_L_MATRIX(N_MODE,N_MODE))
ALLOCATE(HUANG_RHYS_1_I(N_MODE),HUANG_RHYS_2_I(N_MODE))
ALLOCATE(LAMBDA1_I(N_MODE),LAMBDA2_I(N_MODE))
ALLOCATE(DELTA_Q1(N_MODE),DELTA_Q2(N_MODE))
ALLOCATE(DUSHIN_MAT(N_MODE,N_MODE))

ALLOCATE(EV_INI(N_VIB),EV_FINAL(N_VIB))
ALLOCATE(OMEGA1(N_VIB,N_VIB),OMEGA2(N_VIB,N_VIB))
ALLOCATE(S1(N_VIB,N_VIB),S2(N_VIB,N_VIB))
ALLOCATE(B1(N_VIB,N_VIB),B2(N_VIB,N_VIB))
ALLOCATE(D(N_VIB,1))
ALLOCATE(J(N_VIB,N_VIB))
ALLOCATE(Z(N_VIB,1))
IF (USE_HT) THEN
  ALLOCATE(COUP_DER_NM(N_MODE))
  ALLOCATE(COUP_DER_VIB(N_VIB,1))
  ALLOCATE(F_HT_HT(N_VIB,N_VIB))
ELSE
  ALLOCATE(COUP_DER_NM(1))
  ALLOCATE(COUP_DER_VIB(1,1))
  ALLOCATE(F_HT_HT(1,1))
END IF
IF (USE_NASVC) THEN
  ALLOCATE(NAC_SVC_INIT_NM(NUM_STATES_SAME_SPIN_INIT-1,N_MODE))
  ALLOCATE(NAC_SVC_FINAL_NM(NUM_STATES_SAME_SPIN_FINAL-1,N_MODE))
  ALLOCATE(NAC_SVC_INIT_VIB(NUM_STATES_SAME_SPIN_INIT-1,N_VIB,1))
  ALLOCATE(NAC_SVC_FINAL_VIB(NUM_STATES_SAME_SPIN_FINAL-1,N_VIB,1))
  ALLOCATE(SOC_DERIV_INIT_FINALS_NM(NUM_STATES_SAME_SPIN_FINAL-1,N_MODE))
  ALLOCATE(SOC_DERIV_FINAL_INITS_NM(NUM_STATES_SAME_SPIN_INIT-1,N_MODE))
  ALLOCATE(SOC_DERIV_INIT_FINALS_VIB(NUM_STATES_SAME_SPIN_FINAL-1,N_VIB))
  ALLOCATE(SOC_DERIV_FINAL_INITS_VIB(NUM_STATES_SAME_SPIN_INIT-1,N_VIB))
  ALLOCATE(ENERGIES_FOR_NASVC_INIT(NUM_STATES_SAME_SPIN_INIT))
  ALLOCATE(ENERGIES_FOR_NASVC_FINAL(NUM_STATES_SAME_SPIN_FINAL))
  ALLOCATE(SOC_INIT_FINALS(NUM_STATES_SAME_SPIN_FINAL))
  ALLOCATE(SOC_FINAL_INITS(NUM_STATES_SAME_SPIN_INIT))
  ALLOCATE(NAC_SVC_TOTAL_NM(N_MODE))
  ALLOCATE(NAC_MATRIX_SVC_NM(N_MODE))
  ALLOCATE(NAC_SVC_TOTAL_VIB(N_VIB), F_NA_NA(N_VIB,N_VIB))
  ALLOCATE(V_DSO_NA_NM(N_MODE), V_DSO_NA_VIB(N_VIB))
  ALLOCATE(M_HT_NA_NM(N_MODE,N_MODE), M_HT_NA_VIB(N_VIB,N_VIB))
ELSE
  ALLOCATE(NAC_SVC_INIT_NM(1,1))
  ALLOCATE(NAC_SVC_FINAL_NM(1,1))
  ALLOCATE(NAC_SVC_INIT_VIB(1,1,1))
  ALLOCATE(NAC_SVC_FINAL_VIB(1,1,1))
  ALLOCATE(SOC_DERIV_INIT_FINALS_NM(1,1))
  ALLOCATE(SOC_DERIV_FINAL_INITS_NM(1,1))
  ALLOCATE(SOC_DERIV_INIT_FINALS_VIB(1,1))
  ALLOCATE(SOC_DERIV_FINAL_INITS_VIB(1,1))
  ALLOCATE(ENERGIES_FOR_NASVC_INIT(1))
  ALLOCATE(ENERGIES_FOR_NASVC_FINAL(1))
  ALLOCATE(NAC_SVC_TOTAL_NM(1))
  ALLOCATE(NAC_MATRIX_SVC_NM(1))
  ALLOCATE(NAC_SVC_TOTAL_VIB(1))
  ALLOCATE(F_NA_NA(1,1))
  ALLOCATE(V_DSO_NA_NM(1), V_DSO_NA_VIB(1))
  ALLOCATE(M_HT_NA_NM(1,1), M_HT_NA_VIB(1,1))
END IF
IF (USE_NASVC .AND. USE_HT) THEN
  ALLOCATE(F_HT_NA(N_VIB,N_VIB))
ELSE
  ALLOCATE(F_HT_NA(1,1))
END IF

ATOM_MASS1=0
ATOM_MASS2=0
MASS_MAT1=0
MASS_MAT2=0
INIT_FREQ=0
FINAL_FREQ=0
INIT_L_MATRIX=0
FINAL_L_MATRIX=0
HUANG_RHYS_1=0
HUANG_RHYS_1_I=0
HUANG_RHYS_1_EFF=0
DELTA_Q1=0
FREQ1_EFF=0
LAMBDA1_I=0
LAMBDA1_M=0
LAMBDA1_TOT=0
Be=1/(K_b/AU2J)/TEMP
DE=ENERGY_1 - ENERGY_2
OMEGA1=0
OMEGA2=0
Z=0
COUP_DER_NM=0
COUP_DER_VIB=0
SOC_DERIV_INIT_FINALS_NM=0
SOC_DERIV_FINAL_INITS_NM=0
SOC_DERIV_INIT_FINALS_VIB=0
SOC_DERIV_FINAL_INITS_VIB=0
V_DSO_NA_NM=0
V_DSO_NA_VIB=0
M_HT_NA_NM=0
M_HT_NA_VIB=0
S_DSO_NA=0
S_HT_NA=0
SOC_COMPLEX=ISC_SOC
J=0

IF (CAL_REO) THEN

  CALL MASS_MAT(N_ATOMS,N_MODE,INIT_FILENAME,ATOM_MASS1,MASS_MAT1)

  CALL MASS_MAT(N_ATOMS,N_MODE,FINAL_FILENAME,ATOM_MASS2,MASS_MAT2)

  CALL HESS2FREQ(N_ATOMS,N_MODE,HESSIAN_FILE_1,MASS_MAT1,INIT_FREQ,INIT_L_MATRIX)

  CALL HESS2FREQ(N_ATOMS,N_MODE,HESSIAN_FILE_2,MASS_MAT2,FINAL_FREQ,FINAL_L_MATRIX)

  IF (USE_HT) THEN

    IF (SOC_DERIV_MODE == 1 ) THEN
      CALL DR2DQ_TRANS_COMPLEX(N_MODE,MASS_MAT1,INIT_L_MATRIX,FN_SOC_DERIV,COUP_DER_NM)
    ELSE IF (SOC_DERIV_MODE == 2) THEN
      CALL READ_COUPLING_DQ_COMPLEX(N_MODE,FN_SOC_DERIV,COUP_DER_NM)
    ELSE
      WRITE(LOGID,*) "SOC_DERIV_MODE IS NOT WELL SET. PLS CHECK..."
      STOP 200
    END IF
  END IF
  NAC_MATRIX_SVC_NM = 0
  IF (USE_NASVC) THEN
    IF (SOC_DERIV_MODE /= 1) THEN
      WRITE(LOGID,*) "SOC_DERIV_MODE IS NOT WELL SET. It must be 1 for USE_NASVC == .TRUE."
      STOP 200
    END IF

    IF (NUM_STATES_SAME_SPIN_INIT > 1) THEN
      CALL READ_NAC_DR2DQ_FOR_NASVC(NUM_STATES_SAME_SPIN_INIT-1,&
        N_MODE,MASS_MAT1,INIT_L_MATRIX,&
        FN_NAC_SPIN_INIT,NAC_SVC_INIT_NM)

      DO K=1,TARGET_INIT-1
        NAC_SVC_INIT_NM(K,:)=-NAC_SVC_INIT_NM(K,:)
      END DO
    END IF

    IF (NUM_STATES_SAME_SPIN_FINAL > 1) THEN
      CALL READ_NAC_DR2DQ_FOR_NASVC(NUM_STATES_SAME_SPIN_FINAL-1,&
        N_MODE,MASS_MAT1,INIT_L_MATRIX,&
        FN_NAC_SPIN_FINAL,NAC_SVC_FINAL_NM)

      DO K=TARGET_FINAL+1,NUM_STATES_SAME_SPIN_FINAL
        NAC_SVC_FINAL_NM(K-1,:)=-NAC_SVC_FINAL_NM(K-1,:)
      END DO
    END IF

    CALL READ_VECTOR_REAL(NUM_STATES_SAME_SPIN_INIT,FN_ENE_SPIN_INIT,ENERGIES_FOR_NASVC_INIT)
    CALL READ_VECTOR_REAL(NUM_STATES_SAME_SPIN_FINAL,FN_ENE_SPIN_FINAL,ENERGIES_FOR_NASVC_FINAL)

    CALL READ_VECTOR_COMPLEX(NUM_STATES_SAME_SPIN_FINAL,FN_SOC_INIT_FINALS,SOC_INIT_FINALS)
    CALL READ_VECTOR_COMPLEX(NUM_STATES_SAME_SPIN_INIT,FN_SOC_FINAL_INITS,SOC_FINAL_INITS)
    IF (USE_FULL_SVC .AND. USE_HT) THEN
      IF (NUM_STATES_SAME_SPIN_FINAL > 1) THEN
        CALL READ_SOC_DERIV_DR2DQ_FOR_NASVC(NUM_STATES_SAME_SPIN_FINAL,TARGET_FINAL,&
          N_MODE,MASS_MAT1,INIT_L_MATRIX,&
          FN_SOC_DERIV_INIT_FINALS,SOC_DERIV_INIT_FINALS_NM)
      END IF
      IF (NUM_STATES_SAME_SPIN_INIT > 1) THEN
        CALL READ_SOC_DERIV_DR2DQ_FOR_NASVC(NUM_STATES_SAME_SPIN_INIT,TARGET_INIT,&
          N_MODE,MASS_MAT1,INIT_L_MATRIX,&
          FN_SOC_DERIV_FINAL_INITS,SOC_DERIV_FINAL_INITS_NM)
      END IF
    END IF

    NAC_SVC_TOTAL_NM=0
    DO K=1, NUM_STATES_SAME_SPIN_FINAL, 1
      IF (K /= TARGET_FINAL) THEN
        DO I=1, N_MODE, 1
          IF (K < TARGET_FINAL) THEN
            NAC_SVC_TOTAL_NM(I) = NAC_SVC_TOTAL_NM(I) + &
              (SOC_INIT_FINALS(K)*NAC_SVC_FINAL_NM(K,I)*&
              (1/(ENERGIES_FOR_NASVC_FINAL(K) - ENERGIES_FOR_NASVC_FINAL(TARGET_FINAL)) + &
              1/(ENERGIES_FOR_NASVC_FINAL(K) - ENERGIES_FOR_NASVC_INIT(TARGET_INIT))) ) * 0.5
          ELSE
            NAC_SVC_TOTAL_NM(I) = NAC_SVC_TOTAL_NM(I) + &
              (SOC_INIT_FINALS(K)*NAC_SVC_FINAL_NM(K-1,I)*&
              (1/(ENERGIES_FOR_NASVC_FINAL(K) - ENERGIES_FOR_NASVC_FINAL(TARGET_FINAL)) + &
              1/(ENERGIES_FOR_NASVC_FINAL(K) - ENERGIES_FOR_NASVC_INIT(TARGET_INIT))) ) * 0.5
          END IF
        END DO
      END IF
    END DO
    DO K=1, NUM_STATES_SAME_SPIN_INIT, 1
      IF (K /= TARGET_INIT) THEN
        DO I=1, N_MODE, 1
          IF (K < TARGET_INIT) THEN
            NAC_SVC_TOTAL_NM(I) = NAC_SVC_TOTAL_NM(I) + &
              (SOC_FINAL_INITS(K)*NAC_SVC_INIT_NM(K,I)*&
              (1/(ENERGIES_FOR_NASVC_INIT(K) - ENERGIES_FOR_NASVC_FINAL(TARGET_FINAL)) + &
              1/(ENERGIES_FOR_NASVC_INIT(K) - ENERGIES_FOR_NASVC_INIT(TARGET_INIT))) ) * 0.5
          ELSE
            NAC_SVC_TOTAL_NM(I) = NAC_SVC_TOTAL_NM(I) + &
              (SOC_FINAL_INITS(K)*NAC_SVC_INIT_NM(K-1,I)*&
              (1/(ENERGIES_FOR_NASVC_INIT(K) - ENERGIES_FOR_NASVC_FINAL(TARGET_FINAL)) + &
              1/(ENERGIES_FOR_NASVC_INIT(K) - ENERGIES_FOR_NASVC_INIT(TARGET_INIT))) ) * 0.5
          END IF
        END DO
      END IF
    END DO

    IF (USE_FULL_SVC) THEN
      V_DSO_NA_NM=NAC_SVC_TOTAL_NM
      M_HT_NA_NM=0
      S_DSO_NA=0
      S_HT_NA=0
      DO K=1, NUM_STATES_SAME_SPIN_FINAL, 1
        IF (K /= TARGET_FINAL) THEN
          IF (K < TARGET_FINAL) THEN
            ROW_ID = K
          ELSE
            ROW_ID = K-1
          END IF
          DO I=1, N_MODE, 1
            IF (USE_HT) THEN
              DO L=1, N_MODE, 1
                M_HT_NA_NM(I,L) = M_HT_NA_NM(I,L) + &
                  NAC_SVC_FINAL_NM(ROW_ID,I)*SOC_DERIV_INIT_FINALS_NM(ROW_ID,L)*&
                  (1/(ENERGIES_FOR_NASVC_FINAL(K)-ENERGIES_FOR_NASVC_FINAL(TARGET_FINAL)) + &
                  1/(ENERGIES_FOR_NASVC_FINAL(K)-ENERGIES_FOR_NASVC_INIT(TARGET_INIT)))*0.5D0
              END DO
            END IF
          END DO
        END IF
      END DO
      DO K=1, NUM_STATES_SAME_SPIN_INIT, 1
        IF (K /= TARGET_INIT) THEN
          IF (K < TARGET_INIT) THEN
            ROW_ID = K
          ELSE
            ROW_ID = K-1
          END IF
          DO I=1, N_MODE, 1
            IF (USE_HT) THEN
              DO L=1, N_MODE, 1
                M_HT_NA_NM(I,L) = M_HT_NA_NM(I,L) + &
                  NAC_SVC_INIT_NM(ROW_ID,I)*SOC_DERIV_FINAL_INITS_NM(ROW_ID,L)*&
                  (1/(ENERGIES_FOR_NASVC_INIT(K)-ENERGIES_FOR_NASVC_FINAL(TARGET_FINAL)) + &
                  1/(ENERGIES_FOR_NASVC_INIT(K)-ENERGIES_FOR_NASVC_INIT(TARGET_INIT)))*0.5D0
              END DO
              S_HT_NA = S_HT_NA + &
                SOC_DERIV_FINAL_INITS_NM(ROW_ID,I)*NAC_SVC_INIT_NM(ROW_ID,I)*&
                (1/(ENERGIES_FOR_NASVC_INIT(K)-ENERGIES_FOR_NASVC_FINAL(TARGET_FINAL)) + &
                1/(ENERGIES_FOR_NASVC_INIT(K)-ENERGIES_FOR_NASVC_INIT(TARGET_INIT)))*0.5D0
            END IF
          END DO
        END IF
      END DO
    END IF

  END IF

  CALL NOR_DIS_WITH_DUSH(N_ATOMS,N_MODE,INIT_FILENAME,FINAL_FILENAME,INIT_L_MATRIX,FINAL_L_MATRIX,&
    ATOM_MASS1,ATOM_MASS2,MASS_MAT1,MASS_MAT2,DELTA_Q1,'DUSHIN_1.TXT',&
