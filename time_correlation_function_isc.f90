    IF (USE_NASVC) G_FINAL = G_FINAL + 2.D0*REAL(G_1_1_STEP2) + REAL(G_2_1_STEP2)
    IF (USE_HT .AND. USE_NASVC) G_FINAL = G_FINAL &
