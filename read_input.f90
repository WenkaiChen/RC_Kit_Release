SUBROUTINE READ_DATA(INPUT_FILE_NAME,SUB,ISC_SOC,TEMP,ENERGY_1,&
  ENERGY_2,LAMBDA_SUR,LAMBDA_SUR2,N_ATOMS,CAL_REO,&
  CRYSTAL,INIT_FILENAME,FINAL_FILENAME,HESSIAN_FILE_1,HESSIAN_FILE_2,&
  NAC_FILE,NAC_MODE,LOGID,INTEGRAL_STEPS,TIME_STEP,&
  USE_DAMPING_FUNCTION,DAMPING_WIDTH,USE_DUSCHINSKY,USE_HT,USE_NASVC,&
  SIMPLIFIED_SVC,FN_SOC_DERIV,SOC_DERIV_MODE,NUM_STATES_SAME_SPIN_INIT,NUM_STATES_SAME_SPIN_FINAL,&
  FN_NAC_SPIN_INIT,FN_NAC_SPIN_FINAL,FN_ENE_SPIN_INIT,FN_ENE_SPIN_FINAL,TARGET_INIT,&
  TARGET_FINAL,FN_SOC_INIT_FINALS,FN_SOC_FINAL_INITS,NAC_MODE_FOR_NASVC,FN_SOC_DERIV_INIT_FINALS,&
  FN_SOC_DERIV_FINAL_INITS,NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES)
IMPLICIT NONE

CHARACTER*200 :: INPUT_FILE_NAME
COMPLEX(KIND=8) :: ISC_SOC
REAL(KIND=8) :: TEMP
REAL(KIND=8) :: ENERGY_1,ENERGY_2
REAL(KIND=8) :: LAMBDA_SUR,LAMBDA_SUR2
REAL(KIND=8) :: TIME_STEP
REAL(KIND=8) :: DAMPING_WIDTH
INTEGER(KIND=4) :: INTEGRAL_STEPS
INTEGER(KIND=4) :: N_ATOMS
INTEGER(KIND=4) :: SUB
INTEGER(KIND=4) :: LOGID
INTEGER(KIND=4) :: SOC_DERIV_MODE,NAC_MODE,NAC_MODE_FOR_NASVC
INTEGER(KIND=4) :: NUM_STATES_SAME_SPIN_INIT, NUM_STATES_SAME_SPIN_FINAL
INTEGER(KIND=4) :: TARGET_INIT, TARGET_FINAL
CHARACTER*200 :: INIT_FILENAME
CHARACTER*200 :: FINAL_FILENAME
CHARACTER*200 :: HESSIAN_FILE_1
CHARACTER*200 :: HESSIAN_FILE_2
CHARACTER*200 :: NAC_FILE
CHARACTER*200 :: FN_SOC_DERIV
CHARACTER*200 :: FN_NAC_SPIN_INIT
CHARACTER*200 :: FN_NAC_SPIN_FINAL
CHARACTER*200 :: FN_ENE_SPIN_INIT
CHARACTER*200 :: FN_ENE_SPIN_FINAL
CHARACTER*200 :: FN_SOC_INIT_FINALS
CHARACTER*200 :: FN_SOC_FINAL_INITS
CHARACTER*200 :: FN_SOC_DERIV_INIT_FINALS
CHARACTER*200 :: FN_SOC_DERIV_FINAL_INITS
LOGICAL :: CAL_REO
LOGICAL :: CRYSTAL
LOGICAL :: USE_DAMPING_FUNCTION
LOGICAL :: USE_DUSCHINSKY
LOGICAL :: USE_HT,USE_NASVC,SIMPLIFIED_SVC

INTEGER(KIND=4) :: ERROR
INTEGER(KIND=4),PARAMETER :: INPUTID=10
INTEGER(KIND=4) :: NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES(1000)
LOGICAL :: ALIVE
NAMELIST /TEMPERATURE/ TEMP
NAMELIST /INIT_ENERGY/ ENERGY_1
NAMELIST /FINAL_ENERGY/ ENERGY_2
NAMELIST /SPIN_ORBIT_COUPLING/ ISC_SOC
NAMELIST /SURROUDING_LAMBDA/ LAMBDA_SUR,LAMBDA_SUR2
NAMELIST /NUMBER_OF_ATOMS/ N_ATOMS
NAMELIST /FORMULA/ SUB
NAMELIST /INIT_FCHK_NAME/ INIT_FILENAME
NAMELIST /FINAL_FCHK_NAME/ FINAL_FILENAME
NAMELIST /HESSIAN_FILE/ HESSIAN_FILE_1,HESSIAN_FILE_2
NAMELIST /CAL_REO_ENE_OR_NOT/ CAL_REO
NAMELIST /CRY/ CRYSTAL
NAMELIST /NAC_FNAME/ NAC_FILE, NAC_MODE
NAMELIST /INTEGRAL_PARAMETERS/ INTEGRAL_STEPS, TIME_STEP
NAMELIST /DAMPING/ USE_DAMPING_FUNCTION,DAMPING_WIDTH
NAMELIST /SVC/ USE_HT, USE_NASVC, SIMPLIFIED_SVC
NAMELIST /NASVC_PARAMS/ NUM_STATES_SAME_SPIN_INIT, TARGET_INIT,&
  NUM_STATES_SAME_SPIN_FINAL,TARGET_FINAL,&
  FN_NAC_SPIN_INIT, FN_NAC_SPIN_FINAL,&
  FN_ENE_SPIN_INIT, FN_ENE_SPIN_FINAL,&
  FN_SOC_INIT_FINALS, FN_SOC_FINAL_INITS,&
  NAC_MODE_FOR_NASVC,&
  FN_SOC_DERIV_INIT_FINALS, FN_SOC_DERIV_FINAL_INITS
NAMELIST /HTSVC_PARAMS/ FN_SOC_DERIV, SOC_DERIV_MODE
NAMELIST /DUSCH/ USE_DUSCHINSKY
NAMELIST /ZERO_MODE_HUANG_RHYS/ NUM_ZERO_HUANG_MODE,ZERO_HUANG_FACTOR_MODES

OPEN(INPUTID,FILE=INPUT_FILE_NAME,STATUS="OLD",IOSTAT=ERROR)
IF (ERROR/=0) THEN
  WRITE(LOGID,*) "Input file does not exist, please make sure your input file exist."
  STOP
END IF

FN_SOC_DERIV_INIT_FINALS="SOC_Deriv_1.TXT"
FN_SOC_DERIV_FINAL_INITS="SOC_Deriv_2.TXT"
SIMPLIFIED_SVC=.TRUE.

READ(INPUTID,NML=FORMULA)
REWIND(INPUTID)
IF (SUB /= 5 .AND. SUB /= 13) THEN
  WRITE(*,*) "Only SUB=5 (ISC) and SUB=13 (IC) are supported."
  STOP 200
END IF
IF (SUB == 5) THEN
  WRITE(*,*) "ISC Formula from Marian et al. (JCP, 140, 114104, 2014). -- Including Temperature. HT-SVC and/or NA-SVC could be considered."
ELSE IF (SUB == 13) THEN
  WRITE(*,*) "IC Formula from Marian et al. (JCP, 155, 014102, 2021). -- Inclduling Temperature."

END IF

READ(INPUTID,NML=TEMPERATURE)
REWIND(INPUTID)

IF (SUB == 5) THEN
  READ(INPUTID,NML=SPIN_ORBIT_COUPLING)
  REWIND(INPUTID)
ELSE
  ISC_SOC=DCMPLX(0.D0,0.D0)
END IF

READ(INPUTID,NML=INTEGRAL_PARAMETERS)
REWIND(INPUTID)

READ(INPUTID,NML=INIT_ENERGY)
REWIND(INPUTID)

READ(INPUTID,NML=FINAL_ENERGY)
REWIND(INPUTID)

READ(INPUTID,NML=SURROUDING_LAMBDA)
REWIND(INPUTID)

READ(INPUTID,NML=NUMBER_OF_ATOMS)
REWIND(INPUTID)

READ(INPUTID,NML=CAL_REO_ENE_OR_NOT)
REWIND(INPUTID)

READ(INPUTID,NML=CRY)
REWIND(INPUTID)

READ(INPUTID,NML=INIT_FCHK_NAME)
INQUIRE(FILE=INIT_FILENAME,EXIST=ALIVE)
IF (.NOT. (ALIVE)) THEN
  WRITE(LOGID,*) "Initial fchk file does not exist."
  STOP
END IF
REWIND(INPUTID)

READ(INPUTID,NML=FINAL_FCHK_NAME)
INQUIRE(FILE=FINAL_FILENAME,EXIST=ALIVE)
IF (.NOT. (ALIVE)) THEN
  WRITE(LOGID,*) "Final fchk file does not exist."
  STOP
END IF
REWIND(INPUTID)

READ(INPUTID,NML=HESSIAN_FILE)
INQUIRE(FILE=HESSIAN_FILE_1,EXIST=ALIVE)
IF (.NOT. (ALIVE)) THEN
  WRITE(LOGID,*) "hessian file 1 does not exist."
  STOP
END IF
INQUIRE(FILE=HESSIAN_FILE_2,EXIST=ALIVE)
IF (.NOT. (ALIVE)) THEN
  WRITE(LOGID,*) "hessian file 2 does not exist."
  STOP
END IF
REWIND(INPUTID)

IF (SUB == 13) THEN

  READ(INPUTID,NML=NAC_FNAME)
  INQUIRE(FILE=NAC_FILE,EXIST=ALIVE)
  IF ( .NOT. ALIVE ) THEN
    WRITE(LOGID,*) "NAC file does not exist."
    STOP
  END IF
  REWIND(INPUTID)
ELSE
  NAC_FILE="test.txt"
  NAC_MODE=0
END IF

READ(INPUTID,NML=DAMPING)
REWIND(INPUTID)

IF (SUB == 5) THEN
  READ(INPUTID,NML=SVC)
  REWIND(INPUTID)
  IF (.NOT. SIMPLIFIED_SVC .AND. .NOT. (USE_HT .AND. USE_NASVC)) THEN
    WRITE(LOGID,*) "Invalid ISC SVC mode: SIMPLIFIED_SVC=.FALSE. requires USE_HT and USE_NASVC=.TRUE."
    WRITE(*,*) "Invalid ISC SVC mode: SIMPLIFIED_SVC=.FALSE. requires USE_HT and USE_NASVC=.TRUE."
    STOP 200
  END IF
  IF (USE_HT) THEN
    READ(INPUTID,NML=HTSVC_PARAMS)
    INQUIRE(FILE=FN_SOC_DERIV,EXIST=ALIVE)
    IF ( .NOT. ALIVE ) THEN
      WRITE(LOGID,*) "FN_SOC_DERIV does not exist."
      STOP
    END IF
    REWIND(INPUTID)
  ELSE
    FN_SOC_DERIV="test.txt"
    SOC_DERIV_MODE=1

  END IF

  IF (USE_NASVC) THEN
    READ(INPUTID,NML=NASVC_PARAMS)

    INQUIRE(FILE=FN_NAC_SPIN_INIT,EXIST=ALIVE)
    IF ( .NOT. ALIVE ) THEN
      WRITE(LOGID,*) "FN_NAC_SPIN_INIT does not exist."
      STOP
    END IF
    INQUIRE(FILE=FN_NAC_SPIN_FINAL,EXIST=ALIVE)
    IF ( .NOT. ALIVE ) THEN
      WRITE(LOGID,*) "FN_NAC_SPIN_FINAL does not exist."
      STOP
    END IF
    INQUIRE(FILE=FN_ENE_SPIN_INIT,EXIST=ALIVE)
    IF ( .NOT. ALIVE ) THEN
      WRITE(LOGID,*) "FN_ENE_SPIN_INIT does not exist."
      STOP
    END IF
    INQUIRE(FILE=FN_ENE_SPIN_FINAL,EXIST=ALIVE)
    IF ( .NOT. ALIVE ) THEN
      WRITE(LOGID,*) "FN_ENE_SPIN_FINAL does not exist."
      STOP
    END IF
    INQUIRE(FILE=FN_SOC_INIT_FINALS,EXIST=ALIVE)
    IF ( .NOT. ALIVE ) THEN
      WRITE(LOGID,*) "FN_SOC_INIT_FINALS does not exist."
      STOP
    END IF
    INQUIRE(FILE=FN_SOC_FINAL_INITS,EXIST=ALIVE)
    IF ( .NOT. ALIVE ) THEN
      WRITE(LOGID,*) "FN_SOC_FINAL_INITS does not exist."
      STOP
    END IF
    IF (USE_HT .AND. .NOT. SIMPLIFIED_SVC) THEN
      INQUIRE(FILE=FN_SOC_DERIV_INIT_FINALS,EXIST=ALIVE)
      IF ( .NOT. ALIVE ) THEN
        WRITE(LOGID,*) "FN_SOC_DERIV_INIT_FINALS does not exist."
        STOP
      END IF
      INQUIRE(FILE=FN_SOC_DERIV_FINAL_INITS,EXIST=ALIVE)
      IF ( .NOT. ALIVE ) THEN
        WRITE(LOGID,*) "FN_SOC_DERIV_FINAL_INITS does not exist."
        STOP
      END IF
    END IF
    IF (NAC_MODE_FOR_NASVC /= 1) THEN
      WRITE(LOGID,*) "NAC_MODE_FOR_NASVC should be 1 in the current version."
      STOP
    END IF
    REWIND(INPUTID)
  END IF

ELSE
  USE_HT=.FALSE.
  USE_NASVC=.FALSE.
  SIMPLIFIED_SVC=.TRUE.
  NUM_STATES_SAME_SPIN_INIT=1
  TARGET_INIT=1
  NUM_STATES_SAME_SPIN_FINAL=1
  TARGET_FINAL=1
  FN_NAC_SPIN_INIT="NAC_1.TXT"
  FN_NAC_SPIN_FINAL="NAC_2.TXT"
  FN_ENE_SPIN_INIT="ENE_1.TXT"
  FN_ENE_SPIN_FINAL="ENE_2.TXT"
  FN_SOC_INIT_FINALS="SOC_1.TXT"
  FN_SOC_FINAL_INITS="SOC_2.TXT"
  FN_SOC_DERIV_INIT_FINALS="SOC_Deriv_1.TXT"
  FN_SOC_DERIV_FINAL_INITS="SOC_Deriv_2.TXT"
  NAC_MODE_FOR_NASVC=1
  FN_SOC_DERIV="test.txt"
  SOC_DERIV_MODE=1

END IF

READ(INPUTID,NML=DUSCH)
REWIND(INPUTID)

READ(INPUTID,NML=ZERO_MODE_HUANG_RHYS)
REWIND(INPUTID)

CLOSE(INPUTID)
END SUBROUTINE READ_DATA
