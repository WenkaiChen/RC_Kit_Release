SUBROUTINE DIAGSYMAT(N_MODE,MAT,EIGVECMAT,EIGVALARR,ISTAT)
#ifdef USE_CUDA
USE CUDA_FASTPATH, ONLY: CUDA_DIAGSYMAT
#endif
IMPLICIT NONE

INTEGER(KIND=4) :: N_MODE,ISTAT
REAL(KIND=8) :: MAT(N_MODE,N_MODE)
REAL(KIND=8) :: EIGVECMAT(N_MODE,N_MODE)
REAL(KIND=8) :: EIGVALARR(N_MODE)

REAL(KIND=8),ALLOCATABLE :: OFF_DIA(:)
REAL(KIND=8),ALLOCATABLE :: LWORKVEC(:)
INTEGER(KIND=8) :: I

#ifdef USE_CUDA
IF (N_MODE >= 64) THEN
  CALL CUDA_DIAGSYMAT(N_MODE,MAT,EIGVECMAT,EIGVALARR,ISTAT)
  IF (ISTAT == 0) RETURN
END IF
#endif
ALLOCATE(OFF_DIA(N_MODE))
ALLOCATE(LWORKVEC(3*N_MODE-1))
CALL DSYEV('V','U',N_MODE,MAT,N_MODE,EIGVALARR,LWORKVEC,3*N_MODE-1,ISTAT)

EIGVECMAT=MAT
MAT=0D0
FORALL (I=1:N_MODE) MAT(I,I)=EIGVALARR(I)

DEALLOCATE(OFF_DIA)
DEALLOCATE(LWORKVEC)
END SUBROUTINE
