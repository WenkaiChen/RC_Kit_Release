SUBROUTINE READ_NAC_DR2DQ_FOR_NASVC(NUM_STATES,N_MODE,MASS_MAT,L_MATRIX,NAC_SVC_FILE,NAC_SVC)
IMPLICIT NONE

INTEGER(KIND=4) :: NUM_STATES, N_MODE
REAL(KIND=8) :: NAC_SVC(NUM_STATES, N_MODE)
REAL(KIND=8) :: MASS_MAT(N_MODE,N_MODE)
REAL(KIND=8) :: L_MATRIX(N_MODE,N_MODE)
CHARACTER*200 :: NAC_SVC_FILE

INTEGER(KIND=4) :: I,J
INTEGER,PARAMETER :: DR_DERIV_ID = 16
REAL(KIND=8),ALLOCATABLE :: FACTOR_1(:,:)
REAL(KIND=8),ALLOCATABLE :: DR_DERIV_SUBS(:,:)
REAL(KIND=8),PARAMETER :: HBAR=1.054571800D-34

ALLOCATE(FACTOR_1(N_MODE,NUM_STATES))
ALLOCATE(DR_DERIV_SUBS(N_MODE,NUM_STATES))

OPEN(DR_DERIV_ID,FILE=NAC_SVC_FILE,STATUS="OLD")

READ(DR_DERIV_ID,*) DR_DERIV_SUBS
CLOSE(DR_DERIV_ID)

DO J=1,NUM_STATES,1
  DO I=1,N_MODE,1
    FACTOR_1(I,J) = MASS_MAT(I,I)**(-0.5) * DR_DERIV_SUBS(I,J)
  END DO
  NAC_SVC(J,:) = MATMUL(FACTOR_1(:,J),L_MATRIX)
END DO

DEALLOCATE(DR_DERIV_SUBS)
DEALLOCATE(FACTOR_1)
END SUBROUTINE READ_NAC_DR2DQ_FOR_NASVC

SUBROUTINE READ_SOC_DERIV_DR2DQ_FOR_NASVC(NUM_STATES,TARGET_STATE,N_MODE,MASS_MAT,L_MATRIX,&
  SOC_DERIV_FILE,SOC_DERIV)
IMPLICIT NONE

INTEGER(KIND=4) :: NUM_STATES, TARGET_STATE, N_MODE
COMPLEX(KIND=8) :: SOC_DERIV(NUM_STATES-1, N_MODE)
REAL(KIND=8) :: MASS_MAT(N_MODE,N_MODE)
REAL(KIND=8) :: L_MATRIX(N_MODE,N_MODE)
CHARACTER*200 :: SOC_DERIV_FILE

INTEGER(KIND=4) :: I,J,K
INTEGER,PARAMETER :: DR_DERIV_ID = 16
COMPLEX(KIND=8),ALLOCATABLE :: FACTOR_1(:,:)
COMPLEX(KIND=8),ALLOCATABLE :: DR_DERIV_SUBS(:,:)

ALLOCATE(FACTOR_1(N_MODE,NUM_STATES))
ALLOCATE(DR_DERIV_SUBS(N_MODE,NUM_STATES))

OPEN(DR_DERIV_ID,FILE=SOC_DERIV_FILE,STATUS="OLD")

READ(DR_DERIV_ID,*) DR_DERIV_SUBS
CLOSE(DR_DERIV_ID)

K=0
DO J=1,NUM_STATES,1
  IF (J /= TARGET_STATE) THEN
    K=K+1
    DO I=1,N_MODE,1
      FACTOR_1(I,J) = MASS_MAT(I,I)**(-0.5) * DR_DERIV_SUBS(I,J)
    END DO
    SOC_DERIV(K,:) = MATMUL(FACTOR_1(:,J),L_MATRIX)
  END IF
END DO

DEALLOCATE(DR_DERIV_SUBS)
DEALLOCATE(FACTOR_1)
END SUBROUTINE READ_SOC_DERIV_DR2DQ_FOR_NASVC


