SUBROUTINE DR2DQ_TRANS(N_MODE,MASS_MAT,L_MATRIX,DR_DERIV_FILE,DQ_DERIV)

IMPLICIT NONE

INTEGER(KIND=4) :: N_MODE
REAL(KIND=8) :: DQ_DERIV(N_MODE)
REAL(KIND=8) :: MASS_MAT(N_MODE,N_MODE)
REAL(KIND=8) :: L_MATRIX(N_MODE,N_MODE)
CHARACTER*200 :: DR_DERIV_FILE

INTEGER(KIND=4) :: I
INTEGER,PARAMETER :: DR_DERIV_ID = 16
REAL(KIND=8),ALLOCATABLE :: FACTOR_1(:)
REAL(KIND=8),ALLOCATABLE :: DR_DERIV_SUBS(:)
REAL(KIND=8),PARAMETER :: HBAR=1.054571800D-34

ALLOCATE(FACTOR_1(N_MODE))
ALLOCATE(DR_DERIV_SUBS(N_MODE))

OPEN(DR_DERIV_ID,FILE=DR_DERIV_FILE,STATUS="OLD")

READ(DR_DERIV_ID,*) DR_DERIV_SUBS
CLOSE(DR_DERIV_ID)

DO I=1,N_MODE,1
  FACTOR_1(I) = MASS_MAT(I,I)**(-0.5) * DR_DERIV_SUBS(I)
END DO

DQ_DERIV=MATMUL(FACTOR_1,L_MATRIX)

DEALLOCATE(DR_DERIV_SUBS)
DEALLOCATE(FACTOR_1)
END SUBROUTINE DR2DQ_TRANS

